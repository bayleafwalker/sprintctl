_EXPORT_TABLES = ("sprint", "track", "work_item", "event", "claim", "ref", "dep")


def export_ndjson(sqlite_conn: Any, repo_id: str, out: Any) -> dict[str, int]:
    """Export all rows for repo_id from a sqlite connection as NDJSON to file-like out.

    Returns row counts per table.
    """
    import sqlite3 as _sqlite3

    counts: dict[str, int] = {}

    def _row_to_dict(row: _sqlite3.Row) -> dict:
        return dict(row)

    def _sqlite_events(conn: Any, rid: str) -> list[dict]:
        rows = conn.execute("SELECT * FROM event WHERE 1=1 ORDER BY id ASC").fetchall()
        result = []
        for r in rows:
            d = _row_to_dict(r)
            payload_raw = d.get("payload") or "{}"
            try:
                d["payload"] = json.loads(payload_raw) if isinstance(payload_raw, str) else payload_raw
            except json.JSONDecodeError:
                d["payload"] = {}
            d["payload"] = _contracts.canonicalize_event_payload(
                d.get("event_type", ""),
                d["payload"],
            )
            result.append(d)
        return result

    table_queries = {
        "sprint": "SELECT * FROM sprint ORDER BY id ASC",
        "track": "SELECT * FROM track ORDER BY id ASC",
        "work_item": "SELECT * FROM work_item ORDER BY id ASC",
        "claim": "SELECT * FROM claim ORDER BY id ASC",
        "ref": "SELECT * FROM ref ORDER BY id ASC",
        "dep": "SELECT * FROM dep ORDER BY id ASC",
    }

    for table in _EXPORT_TABLES:
        if table == "event":
            rows = _sqlite_events(sqlite_conn, repo_id)
        else:
            raw = sqlite_conn.execute(table_queries[table]).fetchall()
            rows = [_row_to_dict(r) for r in raw]
        for row in rows:
            record = {"table": table, "repo_id": repo_id, "data": row}
            out.write(json.dumps(record) + "\n")
        counts[table] = len(rows)

    return counts


def export_from_postgres(source_conn: Any, repo_id: str) -> list[dict]:
    """Read one repository's rows from another PostgreSQL database's identically
    shaped work tables, in the same table order and record shape ``export_ndjson``
    produces from sqlite -- so both sources can feed the same ``import_ndjson``.

    ``source_conn`` is a plain ``psycopg`` connection (row_factory=dict_row) to
    any database whose ``public`` schema uses this module's DDL -- typically a
    separate, independently-deployed sprintctl authority (e.g. a pre-served-mode
    direct-remote database), not the destination ``store``'s own connection.
    Read-only: never mutates ``source_conn``.
    """
    records: list[dict] = []
    with source_conn.cursor() as cur:
        for table in _EXPORT_TABLES:
            cur.execute(
                f"SELECT * FROM {table} WHERE repo_id = %s ORDER BY id ASC",  # noqa: S608
                (repo_id,),
            )
            for row in cur.fetchall():
                data = dict(row)
                data.pop("repo_id", None)
                records.append({"table": table, "repo_id": repo_id, "data": data})
    return records


def backfill_repo_row_counts(conn: Any, repo_id: str) -> dict[str, int]:
    """Per-table row counts for repo_id, for source/destination parity checks."""
    counts: dict[str, int] = {}
    with conn.cursor() as cur:
        for table in _EXPORT_TABLES:
            cur.execute(f"SELECT COUNT(*) AS n FROM {table} WHERE repo_id = %s", (repo_id,))  # noqa: S608
            row = cur.fetchone()
            counts[table] = row["n"] if row else 0
    return counts


# FK columns that may need id remapping during import, keyed by child table.
_IMPORT_FK_COLUMNS: dict[str, list[tuple[str, str]]] = {
    "track":     [("sprint_id", "sprint")],
    "work_item": [("sprint_id", "sprint"), ("track_id", "track")],
    "event":     [("sprint_id", "sprint"), ("work_item_id", "work_item")],
    "claim":     [("work_item_id", "work_item")],
    "ref":       [("work_item_id", "work_item")],
    "dep":       [("item_id", "work_item"), ("blocked_item_id", "work_item")],
}


def list_repos(conn: Any) -> list[str]:
    """Return all distinct repo_ids present in the sprint table, sorted."""
    with conn.cursor() as cur:
        cur.execute("SELECT DISTINCT repo_id FROM sprint ORDER BY repo_id")
        return [row["repo_id"] for row in cur.fetchall()]


def delete_repo(conn: Any, repo_id: str) -> dict[str, int]:
    """Delete all rows for repo_id across all tables. Returns deleted row counts per table."""
    counts: dict[str, int] = {}
    with conn.cursor() as cur:
        for table in (
            "authority_decision",
            "ingest_record",
            "ingest_stream",
            "ingest_repo_cursor",
        ):
            cur.execute(f"DELETE FROM {table} WHERE repo_id = %s", (repo_id,))  # noqa: S608
            counts[table] = cur.rowcount
        for table in reversed(_EXPORT_TABLES):
            cur.execute(f"DELETE FROM {table} WHERE repo_id = %s", (repo_id,))  # noqa: S608
            counts[table] = cur.rowcount
    conn.commit()
    return counts


def import_ndjson(
    store: PgStore,
    records: list[dict],
    *,
    replace: bool = False,
    remap_ids: bool = False,
    trusted_state_transfer: bool = False,
) -> dict[str, int]:
    """Import NDJSON records into pg, preserving original sqlite integer IDs.

    If replace=True, deletes existing rows for store.repo_id first.
    If remap_ids=True, drops explicit ids and lets the sequence assign fresh ones,
    remapping FK columns accordingly. Use this when importing into a shared database
    where global sequence ids may already be taken by other repos.
    trusted_state_transfer preserves reserved typed events as local authority and
    is only safe when IDs are preserved as part of a backend move. Ordinary
    imports demote them to explicit non-authoritative imported history.
    All work done in a single transaction.
    """
    authority_event_types = {
        _contracts.SPRINT_CLOSE_BOUNDARY_EVENT_TYPE,
        _contracts.CAPABILITY_RECEIPT_DRAFTED_EVENT_TYPE,
    }
    contains_authority_events = any(
        record.get("table") == "event"
        and record.get("data", {}).get("event_type") in authority_event_types
        for record in records
    )
    if trusted_state_transfer and remap_ids and contains_authority_events:
        raise ValueError(
            "trusted state transfer cannot remap IDs when local capability boundary "
            "events are present"
        )
    counts: dict[str, int] = {t: 0 for t in _EXPORT_TABLES}
    # old sqlite id → new postgres id, per table (only populated when remap_ids=True)
    id_maps: dict[str, dict[int, int]] = {t: {} for t in _EXPORT_TABLES}

    with store.conn.cursor() as cur:
        # Serialize against every other concurrent import_ndjson call (any
        # repo) before touching identity sequences: both call sites below
        # read MAX(id) then setval() it, which races across concurrent
        # backfills into this shared database. See IDENTITY_SEQUENCE_LOCK_KEYS.
        cur.execute("SELECT pg_advisory_xact_lock(%s, %s)", IDENTITY_SEQUENCE_LOCK_KEYS)

        if remap_ids:
            # Advance every sequence past the current global max BEFORE any deletes,
            # so the max reflects all committed data. Running this after the replace
            # DELETE would lower the max and could reset the sequence back to 1.
            _advance_identity_sequences(cur, tuple(_EXPORT_TABLES))

        if replace:
            for table in reversed(_EXPORT_TABLES):
                cur.execute(f"DELETE FROM {table} WHERE repo_id = %s", (store.repo_id,))

        for record in records:
            table = record["table"]
            data = dict(record["data"])
            rid = record.get("repo_id", store.repo_id)

            if remap_ids:
                # Remap any FK columns that reference tables we've already inserted.
                for fk_col, ref_table in _IMPORT_FK_COLUMNS.get(table, []):
                    old_ref = data.get(fk_col)
                    if old_ref is not None and old_ref in id_maps[ref_table]:
                        data[fk_col] = id_maps[ref_table][old_ref]
                old_id = data.pop("id", None)
                new_id = _import_row(
                    cur,
                    table,
                    rid,
                    data,
                    returning_id=True,
                    source_event_id=old_id if table == "event" else None,
                    preserve_typed_authority=trusted_state_transfer,
                )
                if old_id is not None and new_id is not None:
                    id_maps[table][old_id] = new_id
            else:
                _import_row(
                    cur,
                    table,
                    rid,
                    data,
                    preserve_typed_authority=trusted_state_transfer,
                )

            counts[table] = counts.get(table, 0) + 1

        # Advance sequences so next auto-generated IDs don't collide.
        _advance_identity_sequences(cur, tuple(_EXPORT_TABLES))

    store.conn.commit()
    return counts


def _import_row(
    cur: Any,
    table: str,
    repo_id: str,
    data: dict,
    *,
    returning_id: bool = False,
    source_event_id: int | None = None,
    preserve_typed_authority: bool = False,
) -> int | None:
    """Insert one row into the named table, using OVERRIDING SYSTEM VALUE for identity columns."""
    row = dict(data)
    row["repo_id"] = repo_id

    # Current PostgreSQL rows require portable aggregate IDs, while old local
    # exports predate that additive column.  Minting on import preserves their
    # identity migration semantics without rejecting a supported archive.
    if table in {"sprint", "work_item"} and row.get("aggregate_uuid") is None:
        row["aggregate_uuid"] = str(uuid4())

    # SQLite stores booleans as integers; coerce to Python bool for psycopg.
    _BOOL_COLUMNS: dict[str, set[str]] = {"claim": {"exclusive"}}
    for col in _BOOL_COLUMNS.get(table, set()):
        if col in row and not isinstance(row[col], bool):
            row[col] = bool(row[col])

    # Canonicalise event payloads during import.
    if table == "event":
        payload = row.get("payload") or {}
        if isinstance(payload, str):
            payload = json.loads(payload)
        event_type = row.get("event_type", "")
        original_event_id = source_event_id if source_event_id is not None else row.get("id")
        if preserve_typed_authority:
            imported_type = event_type
            imported_payload = _contracts.canonicalize_event_payload(event_type, payload)
        else:
            imported_type, imported_payload = _contracts.canonicalize_event_for_archive_import(
                event_type,
                payload,
                original_event_id,
            )
        row["event_type"] = imported_type
        row["payload"] = json.dumps(imported_payload)
        if imported_type != event_type:
            row["source_type"] = "system"

    cols = list(row.keys())
    col_names = ", ".join(cols)
    placeholders = ", ".join(["%s"] * len(cols))
    values = [row[c] for c in cols]
    suffix = " RETURNING id" if returning_id else ""

    if "id" in row:
        cur.execute(
            f"INSERT INTO {table} ({col_names}) OVERRIDING SYSTEM VALUE VALUES ({placeholders}){suffix}",
            values,
        )
    else:
        cur.execute(
            f"INSERT INTO {table} ({col_names}) VALUES ({placeholders}){suffix}",
            values,
        )

    if returning_id:
        result = cur.fetchone()
        return result["id"] if result else None
    return None


