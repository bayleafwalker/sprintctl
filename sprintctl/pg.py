def set_sprint_kind(store: PgStore, sprint_id: int, kind: str) -> None:
    if kind not in SPRINT_KINDS:
        raise ValueError(f"Invalid kind '{kind}'. Must be one of: {', '.join(SPRINT_KINDS)}")
    sprint = get_sprint(store, sprint_id)
    if sprint is None:
        raise ValueError(f"Sprint #{sprint_id} not found")
    with store.conn.cursor() as cur:
        cur.execute(
            "UPDATE sprint SET kind = %s WHERE repo_id = %s AND id = %s",
            (kind, store.repo_id, sprint_id),
        )
    store.conn.commit()


def list_sprints(store: PgStore) -> list[dict]:
    with store.conn.cursor() as cur:
        cur.execute(
            "SELECT * FROM sprint WHERE repo_id = %s ORDER BY created_at DESC",
            (store.repo_id,),
        )
        rows = cur.fetchall()
    return [_norm(r) for r in rows]


def set_sprint_status(store: PgStore, sprint_id: int, new_status: str) -> None:
    sprint = get_sprint(store, sprint_id)
    if sprint is None:
        raise ValueError(f"Sprint #{sprint_id} not found")
    current = sprint["status"]
    if new_status not in SPRINT_TRANSITIONS[current]:
        allowed = sorted(SPRINT_TRANSITIONS[current]) or "none (terminal)"
        raise InvalidTransition(
            f"cannot transition sprint {current} -> {new_status}. Allowed: {allowed}"
        )
    with store.conn.cursor() as cur:
        cur.execute(
            "UPDATE sprint SET status = %s WHERE repo_id = %s AND id = %s",
            (new_status, store.repo_id, sprint_id),
        )
    store.conn.commit()


