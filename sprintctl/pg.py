def _apply_schema_version_14(cur: Any) -> None:
    """Decision core (TS-5) and the capability-receipt fold.

    A work decision is the only writer of terminal status.  ``work_decision``
    is append-only; ``work_item`` gains ``resolution``,
    ``terminal_decision_id`` and ``legacy``.  Every row that exists when this
    runs is legacy and gets no invented decision.  Accepted capability
    receipts in the authority journal become legacy sprint-subject ``accept``
    decisions, and drafted receipt events are recorded as legacy evidence.
    Re-running is a no-op.
    """
    # Existing rows take the column default at ADD time, so adding it with
    # DEFAULT true marks every pre-decision row legacy without a rewrite; new
    # rows then default to false.  IF NOT EXISTS makes a re-run skip both.
    cur.execute(
        """
        ALTER TABLE work_item ADD COLUMN IF NOT EXISTS legacy boolean NOT NULL DEFAULT true;
        ALTER TABLE work_item ALTER COLUMN legacy SET DEFAULT false;
        ALTER TABLE work_item ADD COLUMN IF NOT EXISTS resolution text;
        ALTER TABLE work_item ADD COLUMN IF NOT EXISTS terminal_decision_id bigint;

        CREATE TABLE IF NOT EXISTS work_decision (
            repo_id               text        NOT NULL,
            id                    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            kind                  text        NOT NULL CHECK (
                                     kind IN ('accept', 'reject', 'withdraw', 'supersede', 'revise')
                                  ),
            work_item_id          bigint,
            sprint_id             bigint,
            release_digest        text        CHECK (
                                     release_digest IS NULL OR release_digest ~ '^[0-9a-f]{64}$'
                                  ),
            evidence_digests      jsonb       NOT NULL DEFAULT '[]'::jsonb CHECK (
                                     jsonb_typeof(evidence_digests) = 'array'
                                  ),
            rationale             text        NOT NULL DEFAULT '',
            actor                 text        NOT NULL CHECK (btrim(actor) <> ''),
            superseded_by_item_id bigint,
            legacy_source         text,
            created_at            timestamptz NOT NULL DEFAULT now(),
            UNIQUE (repo_id, id),
            CONSTRAINT work_decision_one_subject
                CHECK ((work_item_id IS NULL) <> (sprint_id IS NULL)),
            CONSTRAINT work_decision_sprint_subject_is_legacy
                CHECK (sprint_id IS NULL OR legacy_source IS NOT NULL),
            CONSTRAINT work_decision_supersede_names_item
                CHECK ((superseded_by_item_id IS NOT NULL) = (kind = 'supersede')),
            CONSTRAINT work_decision_supersede_other_item
                CHECK (superseded_by_item_id IS NULL OR superseded_by_item_id <> work_item_id),
            CONSTRAINT work_decision_item_fk
                FOREIGN KEY (repo_id, work_item_id) REFERENCES work_item(repo_id, id)
                DEFERRABLE INITIALLY DEFERRED,
            CONSTRAINT work_decision_superseded_by_fk
                FOREIGN KEY (repo_id, superseded_by_item_id) REFERENCES work_item(repo_id, id)
                DEFERRABLE INITIALLY DEFERRED,
            CONSTRAINT work_decision_sprint_fk
                FOREIGN KEY (repo_id, sprint_id) REFERENCES sprint(repo_id, id)
        );
        CREATE INDEX IF NOT EXISTS idx_work_decision_repo_item
            ON work_decision(repo_id, work_item_id);
        CREATE INDEX IF NOT EXISTS idx_work_decision_repo_sprint
            ON work_decision(repo_id, sprint_id) WHERE sprint_id IS NOT NULL;

        CREATE TABLE IF NOT EXISTS work_legacy_evidence (
            repo_id        text        NOT NULL,
            event_id       bigint      NOT NULL,
            sprint_id      bigint      NOT NULL,
            payload_sha256 text        NOT NULL CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
            kind           text        NOT NULL,
            recorded_at    timestamptz NOT NULL DEFAULT now(),
            PRIMARY KEY (repo_id, event_id),
            CONSTRAINT work_legacy_evidence_event_fk
                FOREIGN KEY (repo_id, event_id) REFERENCES event(repo_id, id) ON DELETE RESTRICT,
            CONSTRAINT work_legacy_evidence_sprint_fk
                FOREIGN KEY (repo_id, sprint_id) REFERENCES sprint(repo_id, id) ON DELETE RESTRICT
        );

        DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname = 'work_item_resolution_check' AND conrelid = 'work_item'::regclass
            ) THEN
                ALTER TABLE work_item ADD CONSTRAINT work_item_resolution_check
                    CHECK (resolution IS NULL
                           OR resolution IN ('accepted', 'rejected', 'withdrawn', 'superseded'));
            END IF;
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname = 'work_item_terminal_shape' AND conrelid = 'work_item'::regclass
            ) THEN
                ALTER TABLE work_item ADD CONSTRAINT work_item_terminal_shape
                    CHECK ((resolution IS NULL) = (terminal_decision_id IS NULL)
                           AND (terminal_decision_id IS NULL OR status = 'done'));
            END IF;
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname = 'work_item_terminal_decision_fk'
                  AND conrelid = 'work_item'::regclass
            ) THEN
                ALTER TABLE work_item ADD CONSTRAINT work_item_terminal_decision_fk
                    FOREIGN KEY (repo_id, terminal_decision_id)
                    REFERENCES work_decision(repo_id, id)
                    DEFERRABLE INITIALLY DEFERRED;
            END IF;
        END
        $$;
        """
    )
    cur.execute(
        """
        CREATE OR REPLACE FUNCTION sprintctl_work_decision_immutable()
        RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            RAISE EXCEPTION 'work decisions and legacy evidence are append-only (%)', TG_TABLE_NAME;
        END;
        $$;

        -- Row-local rules that compare OLD with NEW run immediately.
        CREATE OR REPLACE FUNCTION sprintctl_work_item_terminal_guard()
        RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            IF TG_OP = 'INSERT' THEN
                IF NEW.legacy
                   AND COALESCE(current_setting('sprintctl.legacy_import', true), '') <> 'on' THEN
                    RAISE EXCEPTION 'work_item.legacy is set only by the schema 14 migration';
                END IF;
                RETURN NEW;
            END IF;
            IF NEW.legacy IS DISTINCT FROM OLD.legacy THEN
                RAISE EXCEPTION 'work_item.legacy is immutable';
            END IF;
            IF OLD.status = 'done' AND NEW.status IS DISTINCT FROM 'done' THEN
                RAISE EXCEPTION 'work item % is terminal; done cannot transition to %',
                    OLD.id, NEW.status;
            END IF;
            -- Becoming done is a decision, for legacy rows too: the legacy
            -- exemption covers only rows that were already done when they
            -- became legacy.  An older runtime that still writes done
            -- directly fails here, loudly, instead of closing work silently.
            IF OLD.status IS DISTINCT FROM 'done' AND NEW.status = 'done'
               AND NEW.terminal_decision_id IS NULL THEN
                RAISE EXCEPTION 'work item % cannot become done without a terminal decision', OLD.id
                    USING ERRCODE = '23514';
            END IF;
            IF OLD.terminal_decision_id IS NOT NULL AND (
                   NEW.terminal_decision_id IS DISTINCT FROM OLD.terminal_decision_id
                   OR NEW.resolution IS DISTINCT FROM OLD.resolution
               ) THEN
                RAISE EXCEPTION 'work item % terminal decision is immutable', OLD.id;
            END IF;
            -- A row that was done before decisions existed keeps no invented
            -- decision.  An open legacy row binds one when it closes above.
            IF OLD.status = 'done' AND OLD.terminal_decision_id IS NULL
               AND NEW.terminal_decision_id IS NOT NULL THEN
                RAISE EXCEPTION 'legacy done work item % takes no decision', OLD.id;
            END IF;
            RETURN NEW;
        END;
        $$;

        -- Cross-row rules are checked at commit against the row as it then
        -- stands, so an import may insert an item before its decision.
        CREATE OR REPLACE FUNCTION sprintctl_work_item_terminal_check()
        RETURNS trigger LANGUAGE plpgsql AS $$
        DECLARE
            item record;
            decision record;
        BEGIN
            SELECT status, legacy, resolution, terminal_decision_id INTO item
            FROM work_item WHERE repo_id = NEW.repo_id AND id = NEW.id;
            IF NOT FOUND THEN
                RETURN NULL;
            END IF;
            IF item.status = 'done' AND item.terminal_decision_id IS NULL AND NOT item.legacy THEN
                RAISE EXCEPTION 'work item % is done without a terminal decision', NEW.id
                    USING ERRCODE = '23514';
            END IF;
            IF item.terminal_decision_id IS NOT NULL THEN
                SELECT kind, work_item_id INTO decision FROM work_decision
                WHERE repo_id = NEW.repo_id AND id = item.terminal_decision_id;
                IF NOT FOUND OR decision.work_item_id IS DISTINCT FROM NEW.id THEN
                    RAISE EXCEPTION 'work item % names a terminal decision about another subject', NEW.id
                        USING ERRCODE = '23514';
                END IF;
                IF item.resolution IS DISTINCT FROM (CASE decision.kind
                        WHEN 'accept' THEN 'accepted'
                        WHEN 'reject' THEN 'rejected'
                        WHEN 'withdraw' THEN 'withdrawn'
                        WHEN 'supersede' THEN 'superseded'
                    END) THEN
                    RAISE EXCEPTION 'work item % resolution % does not match its % decision',
                        NEW.id, item.resolution, decision.kind
                        USING ERRCODE = '23514';
                END IF;
            END IF;
            RETURN NULL;
        END;
        $$;

        -- A terminal item decision must be the one its item is bound to, so
        -- no decision can claim to have closed an item that it did not close.
        CREATE OR REPLACE FUNCTION sprintctl_work_decision_bound_check()
        RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            IF NEW.work_item_id IS NOT NULL AND NEW.kind <> 'revise' AND NOT EXISTS (
                SELECT 1 FROM work_item
                WHERE repo_id = NEW.repo_id AND id = NEW.work_item_id
                  AND terminal_decision_id = NEW.id
            ) THEN
                RAISE EXCEPTION 'terminal decision % is not bound to work item %',
                    NEW.id, NEW.work_item_id
                    USING ERRCODE = '23514';
            END IF;
            RETURN NULL;
        END;
        $$;
        """
    )
    cur.execute("DROP TRIGGER IF EXISTS work_item_terminal_guard ON work_item")
    cur.execute(
        "CREATE TRIGGER work_item_terminal_guard BEFORE INSERT OR UPDATE ON work_item "
        "FOR EACH ROW EXECUTE FUNCTION sprintctl_work_item_terminal_guard()"
    )
    cur.execute("DROP TRIGGER IF EXISTS work_item_terminal_check ON work_item")
    cur.execute(
        "CREATE CONSTRAINT TRIGGER work_item_terminal_check AFTER INSERT OR UPDATE ON work_item "
        "DEFERRABLE INITIALLY DEFERRED "
        "FOR EACH ROW EXECUTE FUNCTION sprintctl_work_item_terminal_check()"
    )
    cur.execute("DROP TRIGGER IF EXISTS work_decision_bound_check ON work_decision")
    cur.execute(
        "CREATE CONSTRAINT TRIGGER work_decision_bound_check AFTER INSERT ON work_decision "
        "DEFERRABLE INITIALLY DEFERRED "
        "FOR EACH ROW EXECUTE FUNCTION sprintctl_work_decision_bound_check()"
    )
