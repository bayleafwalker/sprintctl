def _reservation_event(store: PgStore, row: dict, event_type: str, actor: str, payload: dict) -> None:
    """Append the reservation lifecycle event, as the SQLite backend does.

    Reservations carry no credential, so this trail is the only durable record
    of who reserved, who interrupted whom, and why.  A backend that skipped it
    would give operators a different story depending on where the repository
    happened to live.
    """
    item = get_work_item(store, int(row["work_item_id"]))
    if item is not None:
        create_event(store, item["sprint_id"], actor, event_type,
                     source_type="system", work_item_id=item["id"], payload=payload)


def _reservation_row(store: PgStore, reservation_id: int) -> dict | None:
    with store.conn.cursor() as cur:
        cur.execute("SELECT * FROM reservation WHERE repo_id = %s AND id = %s", (store.repo_id, reservation_id))
        return cur.fetchone()


def get_reservation(store: PgStore, reservation_id: int) -> dict | None:
    row = _reservation_row(store, reservation_id)
    return _reservation.display(row) if row else None


def list_reservations(store: PgStore, work_item_id: int | None = None, *, active_only: bool = True) -> list[dict]:
    clauses, params = ["repo_id = %s"], [store.repo_id]
    if work_item_id is not None:
        clauses.append("work_item_id = %s")
        params.append(work_item_id)
    if active_only:
        clauses.append("state = 'active'")
    with store.conn.cursor() as cur:
        cur.execute("SELECT * FROM reservation WHERE " + " AND ".join(clauses) + " ORDER BY last_activity_at DESC, id DESC", tuple(params))
        return [_reservation.display(row) for row in cur.fetchall()]


def list_reservations_by_sprint(store: PgStore, sprint_id: int, *, active_only: bool = True) -> list[dict]:
    state = "AND r.state = 'active'" if active_only else ""
    with store.conn.cursor() as cur:
        cur.execute(
            "SELECT r.* FROM reservation r JOIN work_item w ON w.repo_id = r.repo_id AND w.id = r.work_item_id "
            "WHERE r.repo_id = %s AND w.sprint_id = %s " + state + " ORDER BY r.last_activity_at DESC, r.id DESC",
            (store.repo_id, sprint_id),
        )
        return [_reservation.display(row) for row in cur.fetchall()]


def reserve(store: PgStore, work_item_id: int, *, actor: str, session_id: str,
            role: str = _reservation.DEFAULT_ROLE, correlation_ref: str | None = None,
            interrupt_existing: bool = False, expected_revision: str | None = None,
            acceptance_contract: dict | None = None) -> dict:
    """Register a reservation, reporting -- never refusing -- overlap.

    Mirrors :func:`sprintctl.db.reserve`: overlapping reservations all commit
    and are returned as the new row's conflict set, and ``interrupt_existing``
    is the separate, deliberate takeover.

    An ``execution`` reservation freezes the item's Release in the same
    transaction (idempotently) and records its digest.  ``expected_revision``
    is the item revision a queued request was made against; a request whose
    basis moved on is refused with :class:`sprintctl.releases.StaleReleaseBasis`
    rather than freezing a revision the requester never saw.
    """
    role = _reservation.normalize_role(role)
    if expected_revision is not None:
        expected_revision = _releases.validate_basis(expected_revision)
    contract = _releases.normalize_acceptance_contract(acceptance_contract)
    if get_work_item(store, work_item_id) is None:
        raise ValueError(f"Work item #{work_item_id} not found")
    now = _reservation.now_text()
    interrupted: list[dict] = []
    try:
        with store.conn.cursor() as cur:
            # Serialize repo-wide reservation admission with maintenance
            # activation.  Activation gates on "zero active reservations"
            # (maintenance_capability), which is a COUNT, not a constraint the
            # database can enforce: without a shared repo-scoped lock an
            # activation that counts zero and a concurrent reserve() can both
            # commit, leaving a live reservation under an active capability.
            # This lock is now the *only* thing reserve() serializes -- item
            # exclusivity is deliberately not enforced.
            cur.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))", (store.repo_id,))
            cur.execute(
                "SELECT 1 FROM maintenance_capability WHERE repo_id = %s "
                "AND state IN ('active','observing') "
                "AND expires_at > statement_timestamp() LIMIT 1",
                (store.repo_id,),
            )
            if cur.fetchone() is not None:
                raise ReservationConflict(
                    "reservations are disabled while an exact-plan maintenance capability is active"
                )
            release_digest = None
            if role == "execution" or expected_revision is not None:
                item, revision, revise_count = _release_basis_locked(
                    cur, store.repo_id, work_item_id
                )
                if expected_revision is not None and not _releases.basis_matches(
                    expected_revision, revision
                ):
                    raise _releases.StaleReleaseBasis(work_item_id, expected_revision, revision)
                if role == "execution":
                    release_digest = _freeze_release_locked(
                        cur, store.repo_id, item, revision, revise_count,
                        actor=actor, acceptance_contract=contract,
                    )
            cur.execute(
                "SELECT * FROM reservation WHERE repo_id = %s AND work_item_id = %s "
                "AND state = 'active' ORDER BY id FOR UPDATE",
                (store.repo_id, work_item_id),
            )
            existing = [dict(row) for row in cur.fetchall()]
            if interrupt_existing:
                interrupted = [row for row in existing if row["role"] == "execution"]
                if interrupted:
                    cur.execute(
                        "UPDATE reservation SET state = 'interrupted', released_at = %s, interruption_reason = %s "
                        "WHERE repo_id = %s AND work_item_id = %s AND state = 'active' AND role = 'execution'",
                        (now, f"interrupted by {actor} ({session_id})", store.repo_id, work_item_id),
                    )
            cur.execute("INSERT INTO reservation(repo_id, work_item_id, session_id, actor, role, state, created_at, last_activity_at, correlation_ref, release_digest) VALUES (%s, %s, %s, %s, %s, 'active', %s, %s, %s, %s) RETURNING id", (store.repo_id, work_item_id, session_id, actor, role, now, now, correlation_ref, release_digest))
            reservation_id = cur.fetchone()["id"]
        store.conn.commit()
    except Exception:
        store.conn.rollback()
        raise
    row = _reservation_row(store, reservation_id)
    assert row is not None
    interrupted_ids = {old["id"] for old in interrupted}
    remaining = [old for old in existing if old["id"] not in interrupted_ids]
    for old in interrupted:
        _reservation_event(store, dict(old), "reservation.interrupted", actor,
                           {"reservation_id": old["id"], "reason": "explicit-takeover", "replacement_id": reservation_id})
    _reservation_event(store, row, "reservation.reserved", actor,
                       {"reservation_id": reservation_id, "session_id": session_id, "role": role,
                        "correlation_ref": correlation_ref, "interrupt_existing": interrupt_existing,
                        "conflicting_reservation_ids": [old["id"] for old in remaining],
                        "release_digest": row["release_digest"]})
    return _reservation.annotate_conflicts(_reservation.display(row), remaining)


def note_session_activity(store: PgStore, work_item_id: int, *, session_id: str | None) -> list[dict]:
    """Bump the activity clock for reservations the caller's session holds.

    Activity is an operational heuristic, not a heartbeat and not proof of
    ownership.  Only the session that registered the reservation (or was
    reassigned it) can move its clock, and only a successful item-scoped
    mutation counts -- reads never do.
    """
    if not session_id:
        return []
    with store.conn.cursor() as cur:
        cur.execute(
            "UPDATE reservation SET last_activity_at = %s "
            "WHERE repo_id = %s AND work_item_id = %s AND session_id = %s AND state = 'active' "
            "RETURNING *",
            (_reservation.now_text(), store.repo_id, work_item_id, session_id),
        )
        rows = cur.fetchall()
    store.conn.commit()
    return [_reservation.display(row) for row in rows]


def touch_reservation(store: PgStore, reservation_id: int, *, session_id: str, correlation_ref: str | None = None) -> dict:
    row = _reservation_row(store, reservation_id)
    if row is None:
        raise ValueError(f"Reservation #{reservation_id} not found")
    if row["state"] != "active":
        raise ValueError(f"Reservation #{reservation_id} is {row['state']}")
    if row["session_id"] != session_id:
        raise ValueError(f"Reservation #{reservation_id} belongs to another session")
    with store.conn.cursor() as cur:
        cur.execute("UPDATE reservation SET last_activity_at = %s, correlation_ref = COALESCE(%s, correlation_ref) WHERE repo_id = %s AND id = %s", (_reservation.now_text(), correlation_ref, store.repo_id, reservation_id))
    store.conn.commit()
    return get_reservation(store, reservation_id)  # type: ignore[return-value]


def reassign_reservation(store: PgStore, reservation_id: int, *, actor: str, session_id: str, correlation_ref: str | None = None) -> dict:
    row = _reservation_row(store, reservation_id)
    if row is None or row["state"] != "active":
        raise ValueError(f"Reservation #{reservation_id} is not active")
    with store.conn.cursor() as cur:
        cur.execute("UPDATE reservation SET actor = %s, session_id = %s, last_activity_at = %s, correlation_ref = COALESCE(%s, correlation_ref) WHERE repo_id = %s AND id = %s", (actor, session_id, _reservation.now_text(), correlation_ref, store.repo_id, reservation_id))
    store.conn.commit()
    updated = _reservation_row(store, reservation_id)
    assert updated is not None
    _reservation_event(store, updated, "reservation.reassigned", actor,
                       {"reservation_id": reservation_id, "previous_actor": row["actor"],
                        "previous_session_id": row["session_id"]})
    return _reservation.display(updated)


def release_reservation(store: PgStore, reservation_id: int, *, actor: str | None = None) -> dict:
    row = _reservation_row(store, reservation_id)
    if row is None:
        raise ValueError(f"Reservation #{reservation_id} not found")
    if row["state"] == "active":
        now = _reservation.now_text()
        with store.conn.cursor() as cur:
            cur.execute("UPDATE reservation SET state = 'released', released_at = %s, last_activity_at = %s WHERE repo_id = %s AND id = %s", (now, now, store.repo_id, reservation_id))
        store.conn.commit()
        updated = _reservation_row(store, reservation_id)
        assert updated is not None
        _reservation_event(store, updated, "reservation.released", actor or row["actor"],
                           {"reservation_id": reservation_id})
    return get_reservation(store, reservation_id)  # type: ignore[return-value]


def sweep_stale_reservations(store: PgStore, *, now: str | None = None,
                             interrupt_after: timedelta | None = None) -> list[dict]:
    """Interrupt long-idle reservations of open items.  Only an explicit sweep calls this.

    Nothing expires in the background: the threshold is operator policy
    (:mod:`sprintctl.reservation_policy`) applied when a sweep runs.
    Reservations of done items are never touched.
    """
    window = _policy.interrupt_after() if interrupt_after is None else interrupt_after
    reason = _policy.sweep_reason(window)
    now = now or _reservation.now_text()
    cutoff = (_reservation.parse_time(now) - window).strftime("%Y-%m-%dT%H:%M:%SZ")
    with store.conn.cursor() as cur:
        # A sweep only touches open work: a done item's history belongs to
        # the decision that closed it, and nothing sweeps it afterwards.
        cur.execute(
            "UPDATE reservation r SET state = 'interrupted', released_at = %s, "
            "interruption_reason = %s WHERE r.repo_id = %s AND r.state = 'active' "
            "AND r.last_activity_at <= %s AND EXISTS (SELECT 1 FROM work_item wi "
            "WHERE wi.repo_id = r.repo_id AND wi.id = r.work_item_id "
            "AND wi.status <> 'done') RETURNING r.*",
            (now, reason, store.repo_id, cutoff),
        )
        rows = cur.fetchall()
    store.conn.commit()
    for row in rows:
        _reservation_event(store, dict(row), "reservation.interrupted", "maintenance",
                           {"reservation_id": row["id"], "reason": reason})
    return [_reservation.display(row, now=now) for row in rows]


