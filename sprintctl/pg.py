def _apply_schema_version_2(cur: Any) -> None:
    """Normalize every legacy v1 deployment before advancing to schema v2."""
    # Phase 26 created this constraint as observation-only.  Authority
    # commands and remote decisions share the immutable remote ledger, but
    # are admitted only by their dedicated arbiter path.
    cur.execute(
        "ALTER TABLE ingest_record "
        "DROP CONSTRAINT IF EXISTS ingest_record_record_class_check"
    )
    cur.execute(
        "ALTER TABLE ingest_record ADD CONSTRAINT ingest_record_record_class_check "
        "CHECK (record_class IN ('observation', 'authority-command', 'remote-decision'))"
    )
    cur.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS idx_ingest_record_repo_offset_unique "
        "ON ingest_record(repo_id, ingest_offset)"
    )
    # P1 ingestion originally persisted only the server receipt timestamp.
    # Preserve producer authorship on upgrade as well as on fresh installs;
    # old rows have no producer timestamp, so their historical receipt time
    # is the only truthful fallback available.
    cur.execute(
        "ALTER TABLE ingest_record "
        "ADD COLUMN IF NOT EXISTS producer_created_at timestamptz"
    )
    cur.execute(
        "UPDATE ingest_record SET producer_created_at = ingested_at "
        "WHERE producer_created_at IS NULL"
    )
    cur.execute(
        "ALTER TABLE ingest_record "
        "ALTER COLUMN producer_created_at SET NOT NULL"
    )
    for table in ("sprint", "work_item"):
        cur.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS aggregate_uuid uuid")
        cur.execute(
            f"UPDATE {table} SET aggregate_uuid = "
            "md5(random()::text || clock_timestamp()::text || id::text)::uuid "
            "WHERE aggregate_uuid IS NULL"
        )
        cur.execute(f"ALTER TABLE {table} ALTER COLUMN aggregate_uuid SET NOT NULL")
        cur.execute(
            f"CREATE UNIQUE INDEX IF NOT EXISTS idx_{table}_aggregate_uuid "
            f"ON {table}(aggregate_uuid)"
        )
    cur.execute("ALTER TABLE ref DROP CONSTRAINT IF EXISTS ref_ref_type_check")
    cur.execute(
        "ALTER TABLE ref ADD CONSTRAINT ref_ref_type_check "
        "CHECK (ref_type IN ('pr', 'issue', 'doc', 'other', "
        "'file', 'glob', 'manifest'))"
    )
    # Advance identity sequences past any ids that were inserted via
    # OVERRIDING SYSTEM VALUE (which bypasses the sequence). Without this,
    # the next nextval call would return a value that conflicts with
    # already-imported data.
    _advance_identity_sequences(cur, ("sprint", "track", "work_item", "event", "ref", "dep"))


def _apply_schema_version_3(cur: Any) -> None:
    """Replace the global public offset with a contiguous repository cursor.

    The old identity value remains as ``ingest_id`` for internal uniqueness.
    Public offsets and every reference to them are translated in one locked
    migration transaction before the schema ledger can advance to version 3.
    """
    cur.execute("LOCK TABLE ingest_record, authority_decision IN ACCESS EXCLUSIVE MODE")
    cur.execute(
        "SELECT EXISTS (SELECT 1 FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = 'ingest_record' "
        "AND column_name = 'ingest_id') AS ingest_id_exists"
    )
    column = cur.fetchone()
    if column and bool(column["ingest_id_exists"]):
        return
    cur.execute(
        "ALTER TABLE authority_decision "
        "DROP CONSTRAINT IF EXISTS authority_decision_record_fk"
    )
    cur.execute("DROP INDEX IF EXISTS idx_ingest_record_repo_offset")
    cur.execute("DROP INDEX IF EXISTS idx_ingest_record_repo_offset_unique")
    cur.execute("ALTER TABLE ingest_record RENAME COLUMN ingest_offset TO ingest_id")
    cur.execute("ALTER TABLE ingest_record ADD COLUMN ingest_offset bigint")
    cur.execute(
        """
        WITH translated AS (
            SELECT ingest_id,
                   row_number() OVER (
                       PARTITION BY repo_id ORDER BY ingest_id
                   )::bigint AS repository_offset
            FROM ingest_record
        )
        UPDATE ingest_record AS record
        SET ingest_offset = translated.repository_offset
        FROM translated
        WHERE record.ingest_id = translated.ingest_id
        """
    )
    cur.execute("ALTER TABLE ingest_record ALTER COLUMN ingest_offset SET NOT NULL")
    cur.execute(
        "ALTER TABLE ingest_record ADD CONSTRAINT ingest_record_ingest_offset_check "
        "CHECK (ingest_offset > 0)"
    )
    cur.execute(
        "CREATE UNIQUE INDEX idx_ingest_record_repo_offset_unique "
        "ON ingest_record(repo_id, ingest_offset)"
    )
    cur.execute(
        "CREATE INDEX idx_ingest_record_repo_offset "
        "ON ingest_record(repo_id, ingest_offset)"
    )
    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS ingest_repo_cursor (
            repo_id text PRIMARY KEY,
            highest_offset bigint NOT NULL DEFAULT 0 CHECK (highest_offset >= 0)
        )
        """
    )
    cur.execute(
        """
        INSERT INTO ingest_repo_cursor (repo_id, highest_offset)
        SELECT repo_id, MAX(ingest_offset)
        FROM ingest_record
        GROUP BY repo_id
        ON CONFLICT (repo_id) DO UPDATE
        SET highest_offset = EXCLUDED.highest_offset
        """
    )
    cur.execute(
        """
        UPDATE authority_decision AS decision
        SET decision_ingest_offset = record.ingest_offset
        FROM ingest_record AS record
        WHERE record.repo_id = decision.repo_id
          AND record.ingest_id = decision.decision_ingest_offset
        """
    )
    cur.execute(
        "ALTER TABLE authority_decision "
        "ADD CONSTRAINT authority_decision_record_fk "
        "FOREIGN KEY (repo_id, decision_ingest_offset) "
        "REFERENCES ingest_record(repo_id, ingest_offset) ON DELETE CASCADE"
    )


