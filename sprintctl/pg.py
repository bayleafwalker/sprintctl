_EXPORT_TABLES = ("sprint", "track", "work_item", "event", "claim", "ref", "dep")


def export_ndjson(sqlite_conn: Any, repo_id: str, out: Any) -> dict[str, int]:
    """Export all rows for repo_id from a sqlite connection as NDJSON to file-like out.

    Returns row counts per table.
    """
    import sqlite3 as _sqlite3

    counts: dict[str, int] = {}

    def _row_to_dict(row: _sqlite3.Row) -> dict:
        return dict(row)

    def _sqlite_events(conn: Any, rid: str) -> list[dict]:
        rows = conn.execute("SELECT * FROM event WHERE 1=1 ORDER BY id ASC").fetchall()
        result = []
        for r in rows:
            d = _row_to_dict(r)
            payload_raw = d.get("payload") or "{}"
            try:
                d["payload"] = json.loads(payload_raw) if isinstance(payload_raw, str) else payload_raw
            except json.JSONDecodeError:
                d["payload"] = {}
            result.append(d)
        return result

    table_queries = {
        "sprint": "SELECT * FROM sprint ORDER BY id ASC",
        "track": "SELECT * FROM track ORDER BY id ASC",
        "work_item": "SELECT * FROM work_item ORDER BY id ASC",
        "claim": "SELECT * FROM claim ORDER BY id ASC",
        "ref": "SELECT * FROM ref ORDER BY id ASC",
        "dep": "SELECT * FROM dep ORDER BY id ASC",
    }

    for table in _EXPORT_TABLES:
        if table == "event":
            rows = _sqlite_events(sqlite_conn, repo_id)
        else:
            raw = sqlite_conn.execute(table_queries[table]).fetchall()
            rows = [_row_to_dict(r) for r in raw]
        for row in rows:
            record = {"table": table, "repo_id": repo_id, "data": row}
            out.write(json.dumps(record) + "\n")
        counts[table] = len(rows)

    return counts


def import_ndjson(store: PgStore, records: list[dict], *, replace: bool = False) -> dict[str, int]:
    """Import NDJSON records into pg, preserving original sqlite integer IDs.

    If replace=True, deletes existing rows for store.repo_id first.
    All work done in a single transaction.
    """
    counts: dict[str, int] = {t: 0 for t in _EXPORT_TABLES}

    with store.conn.cursor() as cur:
        if replace:
            for table in reversed(_EXPORT_TABLES):
                cur.execute(f"DELETE FROM {table} WHERE repo_id = %s", (store.repo_id,))

        for record in records:
            table = record["table"]
            data = record["data"]
            rid = record.get("repo_id", store.repo_id)
            _import_row(cur, table, rid, data)
            counts[table] = counts.get(table, 0) + 1

        # Advance sequences so next auto-generated IDs don't collide.
        for table in _EXPORT_TABLES:
            try:
                cur.execute(
                    f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                    f"COALESCE((SELECT MAX(id) FROM {table} WHERE repo_id = %s), 0) + 1, false)",
                    (store.repo_id,),
                )
            except Exception:
                pass

    store.conn.commit()
    return counts


def _import_row(cur: Any, table: str, repo_id: str, data: dict) -> None:
    """Insert one row into the named table, using OVERRIDING SYSTEM VALUE for identity columns."""
    row = dict(data)
    row["repo_id"] = repo_id

    # Canonicalise event payloads during import.
    if table == "event":
        payload = row.get("payload") or {}
        if isinstance(payload, str):
            payload = json.loads(payload)
        event_type = row.get("event_type", "")
        row["payload"] = json.dumps(_contracts.canonicalize_event_payload(event_type, payload))

    cols = list(row.keys())
    placeholders = ", ".join(["%s"] * len(cols))
    col_names = ", ".join(cols)
    values = [row[c] for c in cols]

    cur.execute(
        f"INSERT INTO {table} ({col_names}) OVERRIDING SYSTEM VALUE VALUES ({placeholders})",
        values,
    )
