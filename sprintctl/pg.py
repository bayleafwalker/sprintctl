_IDENTITY_TABLES = tuple(t for t in _EXPORT_TABLES if t != "work_legacy_evidence")
# work_legacy_evidence has no ``id``; it is keyed and ordered by its event.
_ORDER_COLUMN = {"work_legacy_evidence": "event_id"}


def export_ndjson(sqlite_conn: Any, repo_id: str, out: Any) -> dict[str, int]:
    """Export all rows for repo_id from a sqlite connection as NDJSON to file-like out.

    Returns row counts per table.
    """
    import sqlite3 as _sqlite3

    counts: dict[str, int] = {}

    def _row_to_dict(row: _sqlite3.Row) -> dict:
        return dict(row)

    def _sqlite_events(conn: Any, rid: str) -> list[dict]:
        rows = conn.execute("SELECT * FROM event WHERE 1=1 ORDER BY id ASC").fetchall()
        result = []
        for r in rows:
            d = _row_to_dict(r)
            payload_raw = d.get("payload") or "{}"
            try:
                d["payload"] = json.loads(payload_raw) if isinstance(payload_raw, str) else payload_raw
            except json.JSONDecodeError:
                d["payload"] = {}
            d["payload"] = _contracts.canonicalize_event_payload(
                d.get("event_type", ""),
                d["payload"],
            )
            result.append(d)
        return result

    table_queries = {
        "sprint": "SELECT * FROM sprint ORDER BY id ASC",
        "track": "SELECT * FROM track ORDER BY id ASC",
        "work_item": "SELECT * FROM work_item ORDER BY id ASC",
        "work_release": "SELECT * FROM work_release ORDER BY id ASC",
        "release_commit": "SELECT * FROM release_commit ORDER BY id ASC",
        "work_decision": "SELECT * FROM work_decision ORDER BY id ASC",
        "work_legacy_evidence": "SELECT * FROM work_legacy_evidence ORDER BY event_id ASC",
        "reservation": "SELECT * FROM reservation ORDER BY id ASC",
        "claim_history": "SELECT * FROM claim_history ORDER BY id ASC",
        "ref": "SELECT * FROM ref ORDER BY id ASC",
        "dep": "SELECT * FROM dep ORDER BY id ASC",
    }

    for table in _EXPORT_TABLES:
        if table == "event":
            rows = _sqlite_events(sqlite_conn, repo_id)
        else:
            raw = sqlite_conn.execute(table_queries[table]).fetchall()
            rows = [_row_to_dict(r) for r in raw]
        for row in rows:
            record = {"table": table, "repo_id": repo_id, "data": row}
            out.write(json.dumps(record) + "\n")
        counts[table] = len(rows)

    return counts


def export_from_postgres(source_conn: Any, repo_id: str) -> list[dict]:
    """Read one repository's rows from another PostgreSQL database's identically
    shaped work tables, in the same table order and record shape ``export_ndjson``
    produces from sqlite -- so both sources can feed the same ``import_ndjson``.

    ``source_conn`` is a plain ``psycopg`` connection (row_factory=dict_row) to
    any database whose ``public`` schema uses this module's DDL -- typically a
    separate, independently-deployed sprintctl authority (e.g. a pre-served-mode
    direct-remote database), not the destination ``store``'s own connection.
    Read-only: never mutates ``source_conn``.
    """
    records: list[dict] = []
    with source_conn.cursor() as cur:
        for table in _EXPORT_TABLES:
            cur.execute("SELECT to_regclass(%s) AS relation", (table,))
            if cur.fetchone()["relation"] is None:
                # A source older than schema 14 (15) has no decisions
                # (releases) to carry.
                continue
            cur.execute(
                f"SELECT * FROM {table} WHERE repo_id = %s "  # noqa: S608
                f"ORDER BY {_ORDER_COLUMN.get(table, 'id')} ASC",
                (repo_id,),
            )
            for row in cur.fetchall():
                data = dict(row)
                data.pop("repo_id", None)
                records.append({"table": table, "repo_id": repo_id, "data": data})
    return records


def backfill_repo_row_counts(conn: Any, repo_id: str) -> dict[str, int]:
    """Per-table row counts for repo_id, for source/destination parity checks."""
    counts: dict[str, int] = {}
    with conn.cursor() as cur:
        for table in _EXPORT_TABLES:
            cur.execute("SELECT to_regclass(%s) AS relation", (table,))
            if cur.fetchone()["relation"] is None:
                # A source older than schema 14 has no decision tables.
                counts[table] = 0
                continue
            cur.execute(f"SELECT COUNT(*) AS n FROM {table} WHERE repo_id = %s", (repo_id,))  # noqa: S608
            row = cur.fetchone()
            counts[table] = row["n"] if row else 0
    return counts


