def _decision_row(row: Any) -> dict:
    decision = _norm(row)
    digests = decision.get("evidence_digests")
    if isinstance(digests, str):
        decision["evidence_digests"] = json.loads(digests)
    return decision


def _decide_locked(cur: Any, repo_id: str, item: Any, decision: dict) -> dict:
    """Record one normalized decision about an item already locked FOR UPDATE.

    A terminal kind closes the item in the same statement that binds it to the
    decision, so the item can never be done without one.
    """
    item_id = int(item["id"])
    error = _decisions.decision_error(item, decision)
    if error is not None:
        raise InvalidTransition(error)
    remark = _decisions.is_legacy_remark_target(item)
    superseded_by = decision["superseded_by_item_id"]
    if superseded_by is not None:
        if superseded_by == item_id:
            raise ValueError("an item cannot supersede itself")
        cur.execute(
            "SELECT 1 FROM work_item WHERE repo_id = %s AND id = %s",
            (repo_id, superseded_by),
        )
        if cur.fetchone() is None:
            raise ValueError(f"Superseding item #{superseded_by} not found")
    release_digest = _decision_release_locked(
        cur, repo_id, item_id, decision["release_digest"]
    )
    cur.execute(
        """
        INSERT INTO work_decision (
            repo_id, kind, work_item_id, release_digest, evidence_digests,
            rationale, actor, superseded_by_item_id
        ) VALUES (%s, %s, %s, %s, %s::jsonb, %s, %s, %s)
        RETURNING *
        """,
        (
            repo_id,
            decision["kind"],
            item_id,
            release_digest,
            json.dumps(decision["evidence_digests"]),
            decision["rationale"],
            decision["actor"],
            superseded_by,
        ),
    )
    recorded = _decision_row(cur.fetchone())
    resolution = _decisions.resolution_for(decision["kind"])
    _stamp_awaiting_reports(cur, repo_id, item_id, recorded)
    if remark:
        # A re-mark binds the closure that already happened: the item stays
        # done and keeps its updated_at, the only record of when it closed.
        cur.execute(
            "UPDATE work_item SET resolution = %s, terminal_decision_id = %s "
            "WHERE repo_id = %s AND id = %s",
            (resolution, recorded["id"], repo_id, item_id),
        )
    elif resolution is not None:
        cur.execute(
            "UPDATE work_item SET status = 'done', resolution = %s, "
            "terminal_decision_id = %s, updated_at = now() "
            "WHERE repo_id = %s AND id = %s",
            (resolution, recorded["id"], repo_id, item_id),
        )
        # A terminal item holds no live lease (agentops#2520), whoever
        # decided it; lease settlement overwrites the reason with its own.
        cur.execute(
            "UPDATE work_lease SET state = 'settled', ended_at = clock_timestamp(), "
            "end_reason = %s WHERE repo_id = %s AND work_item_id = %s AND state = 'active'",
            (f"item-{resolution}", repo_id, item_id),
        )
    return recorded


def _stamp_awaiting_reports(cur: Any, repo_id: str, item_id: int, decision: Mapping[str, Any]) -> None:
    """Give outcome reports awaiting verification the decision that landed
    (agentops#2528).  ``accept`` settles them and names the decision;
    any other kind (``reject``, ``withdraw``, ``supersede``, ``revise``)
    ends their wait as ``rejected`` with reason ``decision-<kind>``: the
    report stays as evidence, and schema 18 ties a ``decision_id`` to a
    ``settled`` report only, so the item's decision event is the link.
    Any caller of :func:`_decide_locked` -- the served decision operation,
    ``done`` as an alias, outbox commands -- stamps the same way."""
    if decision["kind"] == "accept":
        cur.execute(
            "UPDATE work_outcome_report SET disposition = 'settled', decision_id = %s "
            "WHERE repo_id = %s AND work_item_id = %s AND disposition = 'awaiting-verification'",
            (int(decision["id"]), repo_id, item_id),
        )
    else:
        cur.execute(
            "UPDATE work_outcome_report SET disposition = 'rejected', reason_code = %s "
            "WHERE repo_id = %s AND work_item_id = %s AND disposition = 'awaiting-verification'",
            (f"decision-{decision['kind']}", repo_id, item_id),
        )


def record_decision(
    store: PgStore,
    item_id: int,
    kind: str,
    *,
    actor: str,
    rationale: str = "",
    evidence_digests: list[str] | None = None,
    release_digest: str | None = None,
    superseded_by_item_id: int | None = None,
    expected_revision: str | None = None,
    idempotency_key: str | None = None,
) -> dict:
    """Record a work decision and apply its terminal effect atomically."""
    recorded, _replayed = record_decision_keyed(
        store,
        item_id,
        kind,
        actor=actor,
        rationale=rationale,
        evidence_digests=evidence_digests,
        release_digest=release_digest,
        superseded_by_item_id=superseded_by_item_id,
        expected_revision=expected_revision,
        idempotency_key=idempotency_key,
    )
    return recorded


def _keyed_decision_locked(cur: Any, repo_id: str, idempotency_key: str) -> dict | None:
    cur.execute(
        "SELECT d.* FROM event e JOIN work_decision d "
        "ON d.repo_id = e.repo_id AND d.id = (e.payload->>'decision_id')::bigint "
        "WHERE e.repo_id = %s AND e.event_type = %s "
        "AND e.payload->>'idempotency_key' = %s ORDER BY e.id LIMIT 1",
        (repo_id, _decisions.ITEM_DECIDED_EVENT_TYPE, idempotency_key),
    )
    row = cur.fetchone()
    return _decision_row(row) if row else None


def record_decision_keyed(
    store: PgStore,
    item_id: int,
    kind: str,
    *,
    actor: str,
    rationale: str = "",
    evidence_digests: list[str] | None = None,
    release_digest: str | None = None,
    superseded_by_item_id: int | None = None,
    expected_revision: str | None = None,
    idempotency_key: str | None = None,
) -> tuple[dict, bool]:
    """Record a decision; return it and whether it replayed an earlier request.

    With ``idempotency_key``, a request that repeats an earlier one under the
    same key returns the decision that request recorded; the same key with a
    different request raises :class:`~sprintctl.decisions.IdempotencyConflict`.
    """
    decision = _decisions.normalize_decision(
        kind,
        actor=actor,
        rationale=rationale,
        evidence_digests=evidence_digests,
        release_digest=release_digest,
        superseded_by_item_id=superseded_by_item_id,
    )
    idempotency_key = _decisions.validate_idempotency_key(idempotency_key)
    if expected_revision is not None:
        expected_revision = validate_item_status_revision(expected_revision)
    try:
        with store.conn.cursor() as cur:
            if idempotency_key is not None:
                # The item lock serializes requests for one item only; a key
                # reused on another item must see the first request's event,
                # so the key itself is locked until this transaction ends.
                cur.execute(
                    "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                    (f"sprintctl-decision-key:{store.repo_id}:{idempotency_key}",),
                )
            cur.execute(
                "SELECT * FROM work_item WHERE repo_id = %s AND id = %s FOR UPDATE",
                (store.repo_id, item_id),
            )
            item = cur.fetchone()
            if item is None:
                raise ValueError(f"Item #{item_id} not found")
            if idempotency_key is not None:
                replayed = _decisions.replay_or_conflict(
                    _keyed_decision_locked(cur, store.repo_id, idempotency_key),
                    item_id,
                    decision,
                    idempotency_key,
                )
                if replayed is not None:
                    store.conn.rollback()
                    return replayed, True
            current_revision = item_status_revision(_norm(item))
            if expected_revision is not None and expected_revision != current_revision:
                raise StatusConflict(
                    f"Item #{item_id} status revision mismatch: "
                    f"expected {expected_revision}, current {current_revision}"
                )
            remark = _decisions.is_legacy_remark_target(item)
            recorded = _decide_locked(cur, store.repo_id, item, decision)
        _insert_event(
            store,
            int(item["sprint_id"]),
            decision["actor"],
            _decisions.ITEM_DECIDED_EVENT_TYPE,
            work_item_id=item_id,
            payload=_decisions.decided_event_payload(
                recorded, idempotency_key, legacy_remark=remark
            ),
        )
        store.conn.commit()
        return recorded, False
    except Exception:
        store.conn.rollback()
        raise


def list_decisions(store: PgStore, item_id: int | None = None) -> list[dict]:
    """Return work decisions for this repository, oldest first."""
    query = "SELECT * FROM work_decision WHERE repo_id = %s"
    params: list[Any] = [store.repo_id]
    if item_id is not None:
        query += " AND work_item_id = %s"
        params.append(item_id)
    with store.conn.cursor() as cur:
        cur.execute(query + " ORDER BY id", params)
        rows = cur.fetchall()
    return [_decision_row(row) for row in rows]


def list_unbound(
    store: PgStore,
    *,
    sprint_id: int | None = None,
    category: str | None = None,
    limit: int | None = None,
) -> dict:
    """Items not bound to a decision, by category (see :mod:`sprintctl.unbound`)."""

    def query_all(sql: str, params: dict) -> list[dict]:
        with store.conn.cursor() as cur:
            cur.execute(sql, params)
            return [_norm(row) for row in cur.fetchall()]

    result = _unbound.list_unbound(
        query_all,
        param=lambda name: f"%({name})s",
        tenant=lambda alias: f"{alias}.repo_id = %(repo_id)s AND",
        params={"repo_id": store.repo_id},
        sprint_id=sprint_id,
        category=category,
        limit=limit,
    )
    # #2446: reported alongside the categories, not one of them and not
    # filtered by --category.  Report-only -- see list_unmet_obligations.
    result["unmet_obligations"] = list_unmet_obligations(store, sprint_id=sprint_id, limit=limit)
    return result


