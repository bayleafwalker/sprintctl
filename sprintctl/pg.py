class _PreparedIngestRecord:
    record: outbox.OutboxRecord
    payload_json: str
    record_sha256: str


def _required_ingest_text(value: Any, field: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"ingest {field} must be a non-empty string")
    return value


def _optional_ingest_text(value: Any, field: str) -> str | None:
    if value is None:
        return None
    return _required_ingest_text(value, field)


def _prepare_ingest_record(
    record: outbox.OutboxRecord,
    *,
    allowed_classes: frozenset[str] = frozenset({"observation"}),
) -> _PreparedIngestRecord:
    """Validate and canonically fingerprint one portable ledger record.

    The public producer-ingestion path keeps its observation-only default.
    The remote authority arbiter opts into authority-command and
    remote-decision records explicitly so a producer cannot smuggle a command
    through the observation synchronization endpoint.
    """
    if not isinstance(record, outbox.OutboxRecord):
        raise TypeError("ingest records must be sprintctl.outbox.OutboxRecord values")
    if record.record_class not in allowed_classes:
        if allowed_classes == frozenset({"observation"}):
            raise ValueError("remote ingestion currently accepts producer observations only")
        allowed = ", ".join(sorted(allowed_classes))
        raise ValueError(f"remote ingestion accepts only these record classes: {allowed}")
    try:
        classified = _contracts.record_class_for_type(record.event_type).value
    except ValueError as exc:
        raise ValueError(f"ingest event_type is not classified: {record.event_type}") from exc
    if classified != record.record_class:
        raise ValueError(
            f"ingest event_type {record.event_type!r} is {classified}, "
            f"not {record.record_class}"
        )
    if isinstance(record.origin_seq, bool) or not isinstance(record.origin_seq, int) or record.origin_seq < 1:
        raise ValueError("ingest origin_seq must be a positive integer")
    if isinstance(record.schema_version, bool) or not isinstance(record.schema_version, int) or record.schema_version < 1:
        raise ValueError("ingest schema_version must be a positive integer")

    origin_stream_id = _required_ingest_text(record.origin_stream_id, "origin_stream_id")
    event_id = _required_ingest_text(record.event_id, "event_id")
    event_type = _required_ingest_text(record.event_type, "event_type")
    actor = _required_ingest_text(record.actor, "actor")
    occurred_at = _required_ingest_text(record.occurred_at, "occurred_at")
    runtime_session_id = _optional_ingest_text(record.runtime_session_id, "runtime_session_id")
    basis_revision = _optional_ingest_text(record.basis_revision, "basis_revision")
    correlation_id = _optional_ingest_text(record.correlation_id, "correlation_id")
    causation_id = _optional_ingest_text(record.causation_id, "causation_id")
    if not isinstance(record.payload, dict):
        raise ValueError("ingest payload must be a JSON object")
    try:
        payload_json = json.dumps(record.payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    except (TypeError, ValueError) as exc:
        raise ValueError("ingest payload must be JSON serializable") from exc
    payload_sha256 = hashlib.sha256(payload_json.encode("utf-8")).hexdigest()
    if record.payload_sha256 != payload_sha256:
        raise ValueError("ingest payload_sha256 does not match the payload")
    created_at = _required_ingest_text(record.created_at, "created_at")

    canonical = {
        "origin_stream_id": origin_stream_id,
        "origin_seq": record.origin_seq,
        "event_id": event_id,
        "schema_version": record.schema_version,
        "record_class": record.record_class,
        "event_type": event_type,
        "actor": actor,
        "runtime_session_id": runtime_session_id,
        "occurred_at": occurred_at,
        "basis_revision": basis_revision,
        "correlation_id": correlation_id,
        "causation_id": causation_id,
        "payload": record.payload,
        "payload_sha256": payload_sha256,
        "created_at": created_at,
    }
    canonical_json = json.dumps(canonical, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    record_sha256 = hashlib.sha256(canonical_json.encode("utf-8")).hexdigest()
    normalized = outbox.OutboxRecord(
        origin_stream_id=origin_stream_id,
        origin_seq=record.origin_seq,
        event_id=event_id,
        schema_version=record.schema_version,
        record_class=record.record_class,
        event_type=event_type,
        actor=actor,
        runtime_session_id=runtime_session_id,
        occurred_at=occurred_at,
        basis_revision=basis_revision,
        correlation_id=correlation_id,
        causation_id=causation_id,
        payload=json.loads(payload_json),
        payload_sha256=payload_sha256,
        created_at=created_at,
    )
    if (
        event_type == _contracts.SESSION_CAPSULE_RECORDED_EVENT_TYPE
        or record.payload.get("schema_version") == "sprintctl-item-evidence/v1"
    ):
        # Import lazily: the typed observation module depends on the producer
        # outbox, while this ingest module is imported by synchronization.
        from . import observations as _observations

        _observations.project_item_evidence(normalized)
    return _PreparedIngestRecord(normalized, payload_json, record_sha256)


def _ingested_record_from_row(row: dict) -> IngestedRecord:
    payload = row["payload"]
    if isinstance(payload, str):
        payload = json.loads(payload)
    record = outbox.OutboxRecord(
        origin_stream_id=row["origin_stream_id"],
        origin_seq=int(row["origin_seq"]),
        event_id=row["event_id"],
        schema_version=int(row["schema_version"]),
        record_class=row["record_class"],
        event_type=row["event_type"],
        actor=row["actor"],
        runtime_session_id=row["runtime_session_id"],
        occurred_at=_iso(row["occurred_at"]) or str(row["occurred_at"]),
        basis_revision=row["basis_revision"],
        correlation_id=row["correlation_id"],
        causation_id=row["causation_id"],
        payload=dict(payload),
        payload_sha256=row["payload_sha256"],
        created_at=_iso(row["producer_created_at"]) or str(row["producer_created_at"]),
    )
    return IngestedRecord(record=record, ingest_offset=int(row["ingest_offset"]))


def _lock_ingest_stream(cur: Any, store: PgStore, origin_stream_id: str) -> tuple[int, bool]:
    """Create then lock one stream row, serializing its sequence admissions.

    Returns ``(highest_origin_seq, bootstrapped)`` where ``bootstrapped`` is
    True only when this call is the very first time the remote authority has
    ever seen this ``origin_stream_id`` (the INSERT actually created the row,
    rather than finding one from a prior admission). Callers use this to
    admit a producer's first-ever record at whatever sequence it presents,
    rather than requiring it to start at 1 -- see ``_admit_request`` and
    ``ingest_records`` for why: a schema migration that introduces or resets
    the ingest ledger (e.g. sprintctl-work schema v4's
    ``repository_ingest_cursor`` capability) leaves every already-active
    local producer outbox with a sequence counter ahead of the remote's now-
    empty history for that stream. Without a first-contact bootstrap, such a
    producer can never admit another record again, because the remote will
    forever expect 1 while the producer will forever send something higher.
    """
    cur.execute(
        """
        INSERT INTO ingest_stream (repo_id, origin_stream_id)
        VALUES (%s, %s)
        ON CONFLICT (repo_id, origin_stream_id) DO NOTHING
        """,
        (store.repo_id, origin_stream_id),
    )
    bootstrapped = cur.rowcount == 1
    cur.execute(
        """
        SELECT highest_origin_seq FROM ingest_stream
        WHERE repo_id = %s AND origin_stream_id = %s
        FOR UPDATE
        """,
        (store.repo_id, origin_stream_id),
    )
    row = cur.fetchone()
    assert row is not None
    return int(row["highest_origin_seq"]), bootstrapped


def _lock_ingest_repo_cursor(cur: Any, store: PgStore) -> int:
    """Create and lock the repository cursor before any producer stream lock."""
    cur.execute(
        """
        INSERT INTO ingest_repo_cursor (repo_id, highest_offset)
        VALUES (%s, 0)
        ON CONFLICT (repo_id) DO NOTHING
        """,
        (store.repo_id,),
    )
    cur.execute(
        """
        SELECT highest_offset FROM ingest_repo_cursor
        WHERE repo_id = %s
        FOR UPDATE
        """,
        (store.repo_id,),
    )
    row = cur.fetchone()
    assert row is not None
    return int(row["highest_offset"])


def _advance_ingest_repo_cursor(cur: Any, store: PgStore, highest_offset: int) -> None:
    cur.execute(
        "UPDATE ingest_repo_cursor SET highest_offset = %s WHERE repo_id = %s",
        (highest_offset, store.repo_id),
    )


_RELEASE_COMMIT_OBSERVED = "release.commit-observed"


def _bind_release_commit_observation(cur: Any, store: PgStore, payload: Any) -> None:
    """Record a harvested ``Vuoro-Release`` trailer against a known release.

    Idempotent (``ON CONFLICT DO NOTHING``).  A digest that is not a release
    of this repository, or a payload of the wrong form, binds nothing: the
    observation stays only as its ingest record (surfaced later as unbound)
    and never fails the batch.
    """
    if not isinstance(payload, dict):
        return
    try:
        digest = _releases.validate_digest(payload.get("release_digest"))
        commit_sha = _releases.validate_commit_sha(payload.get("commit_sha"))
    except ValueError:
        return
    ref = payload.get("ref") if isinstance(payload.get("ref"), str) else None
    remote_hint = (
        payload.get("remote_hint") if isinstance(payload.get("remote_hint"), str) else None
    )
    cur.execute(
        """
        INSERT INTO release_commit (repo_id, release_digest, commit_sha, remote_hint, ref)
        SELECT wr.repo_id, wr.release_digest, %s, %s, %s
        FROM work_release wr
        WHERE wr.repo_id = %s AND wr.release_digest = %s
        ON CONFLICT (repo_id, release_digest, commit_sha) DO NOTHING
        """,
        (commit_sha, remote_hint, ref, store.repo_id, digest),
    )


def ingest_records(store: PgStore, records: list[outbox.OutboxRecord]) -> list[IngestResult]:
    """Atomically admit contiguous producer records into the remote ledger.

    The stream row is the sequence authority.  A retry of an already committed
    identical record returns its original offset; a changed record using the
    same origin tuple or event ID is rejected.  Any detected gap rolls back the
    entire submitted batch, leaving neither a partial ledger append nor an
    advanced stream high-water mark.
    """
    prepared = [_prepare_ingest_record(record) for record in records]
    if not prepared:
        return []
    try:
        with store.conn.cursor() as cur:
            cursor_start = _lock_ingest_repo_cursor(cur, store)
            next_offset = cursor_start
            stream_state = {
                origin_stream_id: _lock_ingest_stream(cur, store, origin_stream_id)
                for origin_stream_id in sorted({item.record.origin_stream_id for item in prepared})
            }
            high_water = {stream_id: state[0] for stream_id, state in stream_state.items()}
            bootstrapped = {stream_id: state[1] for stream_id, state in stream_state.items()}
            results: list[IngestResult] = []
            for item in prepared:
                record = item.record
                cur.execute(
                    """
                    SELECT * FROM ingest_record
                    WHERE repo_id = %s AND origin_stream_id = %s AND origin_seq = %s
                    """,
                    (store.repo_id, record.origin_stream_id, record.origin_seq),
                )
                existing = cur.fetchone()
                if existing is not None:
                    if existing["record_sha256"] != item.record_sha256:
                        raise IngestConflictError(
                            "origin stream sequence already identifies a different record"
                        )
                    existing_record = _ingested_record_from_row(existing)
                    results.append(
                        IngestResult(
                            existing_record.record,
                            existing_record.ingest_offset,
                            duplicate=True,
                        )
                    )
                    continue

                cur.execute(
                    "SELECT record_sha256 FROM ingest_record WHERE repo_id = %s AND event_id = %s",
                    (store.repo_id, record.event_id),
                )
                same_event = cur.fetchone()
                if same_event is not None:
                    raise IngestConflictError("event_id already identifies a different record")

                _admit_sequence(
                    record.origin_stream_id,
                    high_water[record.origin_stream_id],
                    bootstrapped[record.origin_stream_id],
                    record.origin_seq,
                )
                bootstrapped[record.origin_stream_id] = False
                next_offset += 1
                cur.execute(
                    """
                    INSERT INTO ingest_record (
                        repo_id, ingest_offset, origin_stream_id, origin_seq, event_id, schema_version,
                        record_class, event_type, actor, runtime_session_id, occurred_at,
                        basis_revision, correlation_id, causation_id, payload, payload_sha256,
                        record_sha256, producer_created_at
                    ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                    RETURNING *
                    """,
                    (
                        store.repo_id, next_offset, record.origin_stream_id, record.origin_seq, record.event_id,
                        record.schema_version, record.record_class, record.event_type, record.actor,
                        record.runtime_session_id, record.occurred_at, record.basis_revision,
                        record.correlation_id, record.causation_id, item.payload_json,
                        record.payload_sha256, item.record_sha256, record.created_at,
                    ),
                )
                inserted = cur.fetchone()
                cur.execute(
                    """
                    UPDATE ingest_stream SET highest_origin_seq = %s
                    WHERE repo_id = %s AND origin_stream_id = %s
                    """,
                    (record.origin_seq, store.repo_id, record.origin_stream_id),
                )
                high_water[record.origin_stream_id] = record.origin_seq
                result = _ingested_record_from_row(inserted)
                if record.event_type == _RELEASE_COMMIT_OBSERVED:
                    _bind_release_commit_observation(cur, store, record.payload)
                results.append(IngestResult(result.record, result.ingest_offset, duplicate=False))
            if next_offset != cursor_start:
                _advance_ingest_repo_cursor(cur, store, next_offset)
        store.conn.commit()
        return results
    except Exception:
        store.conn.rollback()
        raise


def list_ingested_records(
    store: PgStore, *, after_offset: int = 0, limit: int | None = None
) -> list[IngestedRecord]:
    """Read remote records in server-assigned ingestion order."""
    if isinstance(after_offset, bool) or not isinstance(after_offset, int) or after_offset < 0:
        raise ValueError("after_offset must be a non-negative integer")
    if limit is not None and (isinstance(limit, bool) or not isinstance(limit, int) or limit < 1):
        raise ValueError("limit must be a positive integer")
    query = """
        SELECT * FROM ingest_record
        WHERE repo_id = %s AND ingest_offset > %s
        ORDER BY ingest_offset ASC
    """
    params: list[Any] = [store.repo_id, after_offset]
    if limit is not None:
        query += " LIMIT %s"
        params.append(limit)
    with store.conn.cursor() as cur:
        cur.execute(query, params)
        rows = cur.fetchall()
    return [_ingested_record_from_row(row) for row in rows]


def list_ingest_stream_high_water(store: PgStore) -> dict[str, int]:
    """Return authoritative per-producer stream cursors for one repository.

    This deliberately exposes only each stream's admitted sequence high-water,
    not producer records or cursor mutation.  Recovery uses it when historic
    ledger rows are unavailable but the authority still retains sequence
    admission state.
    """
    with store.conn.cursor() as cur:
        cur.execute(
            """
            SELECT origin_stream_id, highest_origin_seq
            FROM ingest_stream
            WHERE repo_id = %s
            ORDER BY origin_stream_id ASC
            """,
            (store.repo_id,),
        )
        rows = cur.fetchall()
    return {str(row["origin_stream_id"]): int(row["highest_origin_seq"]) for row in rows}


def get_ingest_high_water(store: PgStore) -> int:
    """Return the captured public high-water mark for this repository."""
    with store.conn.cursor() as cur:
        cur.execute(
            "SELECT highest_offset FROM ingest_repo_cursor WHERE repo_id = %s",
            (store.repo_id,),
        )
        row = cur.fetchone()
    return int(row["highest_offset"]) if row is not None else 0


