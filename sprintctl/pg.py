def get_ready_items(store: PgStore, sprint_id: int) -> list[dict]:
    items = list_work_items(store, sprint_id=sprint_id, status="pending")
    ready = []
    for item in items:
        blockers = list_deps_blocking(store, item["id"])
        unresolved = [b for b in blockers if b["blocker_status"] != "done"]
        if not unresolved:
            ready.append({
                **item,
                "blockers_resolved": len(blockers),
                "unresolved_blockers": 0,
                "effective_priority": effective_priority(item),
            })
    ready.sort(
        key=lambda it: (
            it["effective_priority"] is None,
            it["effective_priority"] or 0,
            it["created_at"],
            it["id"],
        )
    )
    return ready


