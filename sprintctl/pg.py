def import_ndjson(
    store: PgStore,
    records: list[dict],
    *,
    replace: bool = False,
    remap_ids: bool = False,
    trusted_state_transfer: bool = False,
) -> dict[str, int]:
    """Import NDJSON records into pg, preserving original sqlite integer IDs.

    If replace=True, deletes existing rows for store.repo_id first.
    If remap_ids=True, drops explicit ids and lets the sequence assign fresh ones,
    remapping FK columns accordingly. Use this when importing into a shared database
    where global sequence ids may already be taken by other repos.
    trusted_state_transfer preserves reserved typed events as local authority and
    is only safe when IDs are preserved as part of a backend move. Ordinary
    imports demote them to explicit non-authoritative imported history.
    All work done in a single transaction.
    """
    authority_event_types = {
        _contracts.SPRINT_CLOSE_BOUNDARY_EVENT_TYPE,
    }
    contains_authority_events = any(
        record.get("table") == "event"
        and record.get("data", {}).get("event_type") in authority_event_types
        for record in records
    )
    if trusted_state_transfer and remap_ids and contains_authority_events:
        raise ValueError(
            "trusted state transfer cannot remap IDs when local sprint-close-boundary "
            "events are present"
        )
    counts: dict[str, int] = {t: 0 for t in _EXPORT_TABLES}
    # old sqlite id → new postgres id, per table (only populated when remap_ids=True)
    id_maps: dict[str, dict[int, int]] = {t: {} for t in _EXPORT_TABLES}

    try:
        with store.conn.cursor() as cur:
            # Rows that were legacy at their source stay legacy: a backend move
            # carries history, it does not create new work.  The switch is
            # transaction-local and only this import sets it.
            cur.execute(f"SET LOCAL {LEGACY_IMPORT_SETTING} = 'on'")
            # Serialize against every other concurrent import_ndjson call (any
            # repo) before touching identity sequences: both call sites below
            # read MAX(id) then setval() it, which races across concurrent
            # backfills into this shared database. See IDENTITY_SEQUENCE_LOCK_KEYS.
            cur.execute("SELECT pg_advisory_xact_lock(%s, %s)", IDENTITY_SEQUENCE_LOCK_KEYS)

            if replace:
                # Decisions and legacy evidence are append-only, and evidence
                # pins the events it names; deleting them is never a
                # replace.  Refuse before anything is written.
                cur.execute(
                    "SELECT (SELECT count(*) FROM work_decision WHERE repo_id = %s) AS decisions, "
                    "(SELECT count(*) FROM work_legacy_evidence WHERE repo_id = %s) AS evidence, "
                    "(SELECT count(*) FROM work_release WHERE repo_id = %s) AS releases",
                    (store.repo_id, store.repo_id, store.repo_id),
                )
                held = cur.fetchone()
                if held["decisions"] or held["evidence"] or held["releases"]:
                    raise ValueError(
                        f"cannot replace repository {store.repo_id!r}: it holds "
                        f"{held['decisions']} work decision(s), {held['evidence']} "
                        f"legacy evidence row(s) and {held['releases']} release(s), "
                        "which are append-only; import into an empty repository instead"
                    )

            if remap_ids:
                # Advance every sequence past the current global max BEFORE any deletes,
                # so the max reflects all committed data. Running this after the replace
                # DELETE would lower the max and could reset the sequence back to 1.
                _advance_identity_sequences(cur, _IDENTITY_TABLES)
                # Items and their terminal decisions name each other.  Reserve
                # the decisions' new ids first so every item binds its decision
                # as it is inserted; both foreign keys are deferred to commit.
                for record in records:
                    if record["table"] == "work_decision" and record["data"].get("id") is not None:
                        cur.execute(
                            "SELECT nextval(pg_get_serial_sequence('work_decision', 'id')) AS id"
                        )
                        id_maps["work_decision"][int(record["data"]["id"])] = int(
                            cur.fetchone()["id"]
                        )

            if replace:
                for table in reversed(_EXPORT_TABLES):
                    cur.execute(f"DELETE FROM {table} WHERE repo_id = %s", (store.repo_id,))

            for record in records:
                table = record["table"]
                data = dict(record["data"])
                rid = record.get("repo_id", store.repo_id)

                if table == "work_item" and "legacy" not in data:
                    # An archive that predates decisions holds only legacy
                    # rows.  A row that already carries decision columns is
                    # from a later archive, and a missing flag there is not
                    # read as legacy: the legacy exemptions cover only rows
                    # that were legacy at their source.
                    data["legacy"] = not (
                        "terminal_decision_id" in data or "resolution" in data
                    )
                if remap_ids:
                    # Remap any FK columns that reference tables we've already inserted.
                    for fk_col, ref_table in _IMPORT_FK_COLUMNS.get(table, []):
                        old_ref = data.get(fk_col)
                        if old_ref is not None and old_ref in id_maps[ref_table]:
                            data[fk_col] = id_maps[ref_table][old_ref]
                    if table == "work_decision" and data.get("id") is not None:
                        # Keep the id reserved above; its item already names it.
                        _import_row(cur, table, rid, {**data, "id": id_maps[table][int(data["id"])]})
                    else:
                        old_id = data.pop("id", None)
                        new_id = _import_row(
                            cur,
                            table,
                            rid,
                            data,
                            returning_id=table in _IDENTITY_TABLES,
                            source_event_id=old_id if table == "event" else None,
                            preserve_typed_authority=trusted_state_transfer,
                        )
                        if old_id is not None and new_id is not None:
                            id_maps[table][old_id] = new_id
                else:
                    _import_row(
                        cur,
                        table,
                        rid,
                        data,
                        preserve_typed_authority=trusted_state_transfer,
                    )

                counts[table] = counts.get(table, 0) + 1

            # Advance sequences so next auto-generated IDs don't collide.
            _advance_identity_sequences(cur, _IDENTITY_TABLES)
            # Settle the deferred decision constraints here, so a violation
            # names this import instead of surfacing at a later commit.
            cur.execute("SET CONSTRAINTS ALL IMMEDIATE")

        store.conn.commit()
    except Exception:
        store.conn.rollback()
        raise
    return counts


def _import_row(
    cur: Any,
    table: str,
    repo_id: str,
    data: dict,
    *,
    returning_id: bool = False,
    source_event_id: int | None = None,
    preserve_typed_authority: bool = False,
) -> int | None:
    """Insert one row into the named table, using OVERRIDING SYSTEM VALUE for identity columns."""
    row = dict(data)
    row["repo_id"] = repo_id

    # Current PostgreSQL rows require portable aggregate IDs, while old local
    # exports predate that additive column.  Minting on import preserves their
    # identity migration semantics without rejecting a supported archive.
    if table in {"sprint", "work_item"} and row.get("aggregate_uuid") is None:
        row["aggregate_uuid"] = str(uuid4())

    # SQLite stores booleans as integers; coerce to Python bool for psycopg.
    _BOOL_COLUMNS: dict[str, set[str]] = {
        "claim_history": {"exclusive"},
        "work_item": {"legacy"},
    }
    for col in _BOOL_COLUMNS.get(table, set()):
        if col in row and not isinstance(row[col], bool):
            row[col] = bool(row[col])

    # Canonicalise event payloads during import.
    if table == "event":
        payload = row.get("payload") or {}
        if isinstance(payload, str):
            payload = json.loads(payload)
        event_type = row.get("event_type", "")
        original_event_id = source_event_id if source_event_id is not None else row.get("id")
        if preserve_typed_authority:
            imported_type = event_type
            imported_payload = _contracts.canonicalize_event_payload(event_type, payload)
        else:
            imported_type, imported_payload = _contracts.canonicalize_event_for_archive_import(
                event_type,
                payload,
                original_event_id,
            )
        row["event_type"] = imported_type
        row["payload"] = json.dumps(imported_payload)
        if imported_type != event_type:
            row["source_type"] = "system"
    if table == "work_decision":
        digests = row.get("evidence_digests")
        if not isinstance(digests, str):
            row["evidence_digests"] = json.dumps(digests if digests is not None else [])
    if table == "work_release":
        for column in ("acceptance_contract", "context_refs"):
            if column in row and not isinstance(row[column], str):
                row[column] = json.dumps(row[column])

    cols = list(row.keys())
    col_names = ", ".join(cols)
    placeholders = ", ".join(["%s"] * len(cols))
    values = [row[c] for c in cols]
    suffix = " RETURNING id" if returning_id else ""

    if "id" in row:
        cur.execute(
            f"INSERT INTO {table} ({col_names}) OVERRIDING SYSTEM VALUE VALUES ({placeholders}){suffix}",
            values,
        )
    else:
        cur.execute(
            f"INSERT INTO {table} ({col_names}) VALUES ({placeholders}){suffix}",
            values,
        )

    if returning_id:
        result = cur.fetchone()
        return result["id"] if result else None
    return None


