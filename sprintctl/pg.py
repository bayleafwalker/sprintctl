def set_sprint_status(
    store: PgStore,
    sprint_id: int,
    new_status: str,
    *,
    expected_revision: str | None = None,
) -> None:
    if expected_revision is not None:
        expected_revision = validate_sprint_status_revision(expected_revision)
    try:
        with store.conn.cursor() as cur:
            # The row lock makes the status comparison and update one
            # single-object CAS operation across independent connections.
            cur.execute(
                "SELECT * FROM sprint WHERE repo_id = %s AND id = %s FOR UPDATE",
                (store.repo_id, sprint_id),
            )
            row = cur.fetchone()
            if row is None:
                raise ValueError(f"Sprint #{sprint_id} not found")
            sprint = _norm(row)
            current = sprint["status"]
            current_revision = sprint_status_revision(sprint)
            if expected_revision is not None and expected_revision != current_revision:
                raise StatusConflict(
                    f"Sprint #{sprint_id} status revision mismatch: "
                    f"expected {expected_revision}, current {current_revision}"
                )
            if new_status not in SPRINT_TRANSITIONS[current]:
                allowed = sorted(SPRINT_TRANSITIONS[current]) or "none (terminal)"
                raise InvalidTransition(
                    f"cannot transition sprint {current} -> {new_status}. Allowed: {allowed}"
                )
            cur.execute(
                "UPDATE sprint SET status = %s WHERE repo_id = %s AND id = %s",
                (new_status, store.repo_id, sprint_id),
            )
        store.conn.commit()
    except Exception:
        store.conn.rollback()
        raise


def activate_sprint(store: PgStore, sprint_id: int, actor: str, context: str = "sprintctl:sprint-activate") -> dict:
    """Activate a planned sprint through the domain-owned SQL command handler.

    The transition rule (planned -> active only, archives rejected), the kind
    flip to active_sprint, and the sprint-activated ledger event live in
    sprintctl_sprint_activate() in the schema, so every write surface (this
    wrapper, the cockpit API) shares one implementation.
    """
    try:
        with store.conn.cursor() as cur:
            cur.execute(
                "SELECT * FROM sprintctl_sprint_activate(%s, %s, %s, %s)",
                (store.repo_id, sprint_id, actor, context),
            )
            row = cur.fetchone()
    except Exception as exc:
        sqlstate = getattr(exc, "sqlstate", None)
        store.conn.rollback()
        message = getattr(getattr(exc, "diag", None), "message_primary", None) or str(exc)
        if sqlstate == "SP404":
            raise ValueError(message) from exc
        if sqlstate == "SP409":
            raise InvalidTransition(message) from exc
        raise
    store.conn.commit()
    return _norm(row)


