def get_connection(url: str) -> PgStore:
    if not _PSYCOPG_AVAILABLE:  # pragma: no cover
        raise RuntimeError("psycopg is not installed. Install sprintctl[remote].")
    repo_id = _repo_id_from_cwd()
    conn = psycopg.connect(url, row_factory=dict_row)
    return PgStore(conn=conn, repo_id=repo_id)


def _repo_id_from_cwd() -> str:
    from pathlib import Path
    from . import backend as _backend
    _, repo_id, _ = _backend.resolve_repo_identity(Path.cwd())
    return repo_id or "unknown"


def init_db(store: PgStore) -> None:
    with store.conn.cursor() as cur:
        cur.execute(_DDL)
    store.conn.commit()


# ---------------------------------------------------------------------------
# Row normalisation
# ---------------------------------------------------------------------------

def _iso(value: Any) -> str | None:
    if value is None:
        return None
    if isinstance(value, datetime):
        if value.tzinfo is None:
            value = value.replace(tzinfo=timezone.utc)
        return value.strftime("%Y-%m-%dT%H:%M:%SZ")
    return str(value)


def _norm(row: dict) -> dict:
    """Normalise a pg row: datetimes → ISO strings, date → ISO string."""
    import datetime as _dt
    out: dict = {}
    for k, v in row.items():
        if isinstance(v, datetime):
            out[k] = _iso(v)
        elif isinstance(v, _dt.date):
            out[k] = v.isoformat()
        else:
            out[k] = v
    return out


