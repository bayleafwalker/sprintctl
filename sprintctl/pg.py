def _fold_capability_receipts(cur: Any) -> dict[str, int]:
    """Fold the retired capability-receipt surface into decisions and evidence.

    Accepted receipts live in the authority journal (``ingest_record`` plus
    ``authority_decision``), not only in ``event``; each accepted request
    becomes one legacy sprint-subject ``accept`` decision whose evidence is the
    receipt digest and the admitted request's record digest.  The request
    digest is also the idempotency key.  Drafted receipt events stay where
    they are and are listed in ``work_legacy_evidence``.
    """
    cur.execute(
        """
        SELECT DISTINCT ON (ad.repo_id, ad.request_event_id)
               ad.repo_id, ad.request_event_id, ad.request_record_sha256,
               ad.decided_at, ad.effect, req.actor, req.payload AS request_payload
        FROM authority_decision ad
        JOIN ingest_record req
          ON req.repo_id = ad.repo_id AND req.event_id = ad.request_event_id
        JOIN ingest_record dec
          ON dec.repo_id = ad.repo_id AND dec.ingest_offset = ad.decision_ingest_offset
        WHERE ad.outcome = 'accepted'
          AND (req.event_type = ANY(%s) OR dec.event_type = ANY(%s))
        ORDER BY ad.repo_id, ad.request_event_id
        """,
        (list(_LEGACY_RECEIPT_COMMAND_TYPES), list(_LEGACY_RECEIPT_COMMAND_TYPES)),
    )
    accepted = cur.fetchall()
    folded = 0
    for row in accepted:
        effect = row["effect"] if isinstance(row["effect"], dict) else json.loads(row["effect"] or "{}")
        request = row["request_payload"]
        if isinstance(request, str):
            request = json.loads(request)
        command_payload = request.get("payload") if isinstance(request, dict) else None
        pointer = command_payload.get("pointer") if isinstance(command_payload, dict) else None
        sprint_id = effect.get("sprint_id")
        if sprint_id is None:
            refs = request.get("refs") if isinstance(request, dict) else None
            aggregate_uuid = refs.get("aggregate_uuid") if isinstance(refs, dict) else None
            if aggregate_uuid is not None:
                cur.execute(
                    "SELECT id FROM sprint WHERE repo_id = %s AND aggregate_uuid = %s",
                    (row["repo_id"], aggregate_uuid),
                )
                found = cur.fetchone()
                sprint_id = found["id"] if found else None
        if sprint_id is None:
            raise RuntimeError(
                "cannot fold accepted capability receipt "
                f"{row['request_event_id']!r}: its sprint cannot be resolved"
            )
        cur.execute(
            "SELECT 1 FROM sprint WHERE repo_id = %s AND id = %s",
            (row["repo_id"], int(sprint_id)),
        )
        if cur.fetchone() is None:
            raise RuntimeError(
                "cannot fold accepted capability receipt "
                f"{row['request_event_id']!r}: sprint #{sprint_id} does not exist"
            )
        request_digest = row["request_record_sha256"]
        cur.execute(
            "SELECT 1 FROM work_decision WHERE repo_id = %s AND legacy_source = %s "
            "AND evidence_digests @> %s::jsonb",
            (
                row["repo_id"],
                _decisions.LEGACY_CAPABILITY_RECEIPT_SOURCE,
                json.dumps([request_digest]),
            ),
        )
        if cur.fetchone() is not None:
            continue
        digests: list[str] = []
        for candidate in (
            effect.get("receipt_sha256"),
            pointer.get("receipt_sha256") if isinstance(pointer, dict) else None,
            request_digest,
        ):
            if isinstance(candidate, str) and len(candidate) == 64 and candidate not in digests:
                digests.append(candidate)
        cur.execute(
            """
            INSERT INTO work_decision (
                repo_id, kind, sprint_id, evidence_digests, rationale, actor,
                legacy_source, created_at
            ) VALUES (%s, 'accept', %s, %s::jsonb, %s, %s, %s, %s)
            """,
            (
                row["repo_id"],
                int(sprint_id),
                json.dumps(digests),
                "folded from capability-receipt authority request "
                f"{row['request_event_id']}",
                row["actor"],
                _decisions.LEGACY_CAPABILITY_RECEIPT_SOURCE,
                row["decided_at"],
            ),
        )
        folded += 1
    cur.execute(
        """
        SELECT e.repo_id, e.id, e.sprint_id, e.event_type, e.payload
        FROM event e
        WHERE e.event_type = ANY(%s)
          AND NOT EXISTS (
              SELECT 1 FROM work_legacy_evidence w
              WHERE w.repo_id = e.repo_id AND w.event_id = e.id
          )
        ORDER BY e.id
        """,
        (list(_LEGACY_RECEIPT_DRAFTED_EVENT_TYPES),),
    )
    drafted = cur.fetchall()
    for row in drafted:
        cur.execute(
            "INSERT INTO work_legacy_evidence (repo_id, event_id, sprint_id, payload_sha256, kind) "
            "VALUES (%s, %s, %s, %s, %s) ON CONFLICT (repo_id, event_id) DO NOTHING",
            (
                row["repo_id"],
                row["id"],
                row["sprint_id"],
                _decisions.legacy_evidence_digest(row["payload"]),
                row["event_type"],
            ),
        )
    return {"accept_decisions": folded, "drafted_evidence": len(drafted)}


def refold_capability_receipts(conn: Any) -> dict[str, int]:
    """Fold capability receipts written after schema 14 was applied.

    During a rolling deploy an old (<= 0.3.7) pod can still record a drafted
    or accepted receipt after the migration ran.  The fold is idempotent, so
    running it again once the new pods are up picks those up and leaves the
    rest untouched.  ``migrate_schema`` calls this whenever the schema is
    already at 14 or later, so the rollout step is a second
    ``sprintctl remote-schema migrate``.  Commits on success.
    """
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT pg_advisory_xact_lock(%s, %s)",
                _pg_migrations.SCHEMA_MIGRATION_LOCK_KEYS,
            )
            result = _fold_capability_receipts(cur)
        conn.commit()
        return result
    except Exception:
        conn.rollback()
        raise


def _apply_schema_version_15(cur: Any) -> None:
    """Release (S3 PR2): an execution reservation freezes what it picked up.

    ``work_release`` is append-only and content-addressed by
    ``release_digest``.  ``release_commit`` (append-only) is installed empty
    for the commit observations a later release will record.  Reservations
    gain the digest of the release they froze.  No existing row changes, so
    re-running is a no-op.
    """
    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS work_release (
            repo_id             text        NOT NULL,
            id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            work_item_id        bigint      NOT NULL,
            item_revision       text        NOT NULL CHECK (
                                    item_revision ~ '^item:[0-9a-fA-F-]{36}@description:v[0-9]+@sha256:[0-9a-f]{64}@revise:[0-9]+$'
                                ),
            revise_count        integer     NOT NULL DEFAULT 0 CHECK (revise_count >= 0),
            release_digest      text        NOT NULL CHECK (release_digest ~ '^[0-9a-f]{64}$'),
            acceptance_contract jsonb       NOT NULL DEFAULT '{"review_required": true}'::jsonb
                                CHECK (jsonb_typeof(acceptance_contract) = 'object'),
            context_refs        jsonb       NOT NULL DEFAULT '[]'::jsonb
                                CHECK (jsonb_typeof(context_refs) = 'array'),
            created_at          timestamptz NOT NULL DEFAULT now(),
            actor               text        NOT NULL CHECK (btrim(actor) <> ''),
            UNIQUE (repo_id, id),
            CONSTRAINT work_release_digest_unique UNIQUE (repo_id, release_digest),
            -- The target of reservation_release_item_fk, so a reservation can
            -- only name a release of its own item.
            CONSTRAINT work_release_item_digest_unique
                UNIQUE (repo_id, work_item_id, release_digest),
            CONSTRAINT work_release_revise_count_matches
                CHECK (item_revision LIKE '%@revise:' || revise_count::text),
            CONSTRAINT work_release_item_fk
                FOREIGN KEY (repo_id, work_item_id) REFERENCES work_item(repo_id, id)
        );
        CREATE INDEX IF NOT EXISTS idx_work_release_repo_item
            ON work_release(repo_id, work_item_id, revise_count);

        CREATE TABLE IF NOT EXISTS release_commit (
            repo_id        text        NOT NULL,
            id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            release_digest text        NOT NULL,
            commit_sha     text        NOT NULL CHECK (commit_sha ~ '^[0-9a-f]{40}$'),
            remote_hint    text,
            ref            text,
            observed_at    timestamptz NOT NULL DEFAULT now(),
            UNIQUE (repo_id, id),
            CONSTRAINT release_commit_unique UNIQUE (repo_id, release_digest, commit_sha),
            CONSTRAINT release_commit_release_fk
                FOREIGN KEY (repo_id, release_digest)
                REFERENCES work_release(repo_id, release_digest)
        );

        ALTER TABLE reservation ADD COLUMN IF NOT EXISTS release_digest text;
        CREATE INDEX IF NOT EXISTS idx_reservation_repo_release
            ON reservation(repo_id, release_digest) WHERE release_digest IS NOT NULL;

        DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname = 'work_release_item_digest_unique'
                  AND conrelid = 'work_release'::regclass
            ) THEN
                ALTER TABLE work_release ADD CONSTRAINT work_release_item_digest_unique
                    UNIQUE (repo_id, work_item_id, release_digest);
            END IF;
            -- An earlier draft of this migration keyed the reservation's
            -- release by digest alone, which let it name another item's.
            ALTER TABLE reservation DROP CONSTRAINT IF EXISTS reservation_release_fk;
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname = 'reservation_release_item_fk'
                  AND conrelid = 'reservation'::regclass
            ) THEN
                ALTER TABLE reservation ADD CONSTRAINT reservation_release_item_fk
                    FOREIGN KEY (repo_id, work_item_id, release_digest)
                    REFERENCES work_release(repo_id, work_item_id, release_digest);
            END IF;
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname = 'reservation_release_execution_only'
                  AND conrelid = 'reservation'::regclass
            ) THEN
                ALTER TABLE reservation ADD CONSTRAINT reservation_release_execution_only
                    CHECK (release_digest IS NULL OR role = 'execution');
            END IF;
        END
        $$;

        CREATE OR REPLACE FUNCTION sprintctl_release_immutable()
        RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            RAISE EXCEPTION 'releases and release commits are append-only (%)', TG_TABLE_NAME;
        END;
        $$;

        -- A runtime older than 15 reserves without freezing a release and
        -- decides without binding one.  These guards make such a pod fail
        -- loudly during a rolling deploy instead of writing rows that later
        -- decisions would bind wrongly.  Rows that already exist (legacy
        -- execution reservations with no digest, older decisions) are never
        -- re-checked; archive import and recovery carry history as it was.
        CREATE OR REPLACE FUNCTION sprintctl_reservation_release_guard()
        RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            IF TG_OP = 'INSERT' THEN
                IF NEW.role = 'execution' AND NEW.release_digest IS NULL
                   AND COALESCE(current_setting('sprintctl.legacy_import', true), '') <> 'on' THEN
                    RAISE EXCEPTION 'an execution reservation must freeze a release (schema 15)'
                        USING ERRCODE = '23514';
                END IF;
            ELSIF NEW.release_digest IS DISTINCT FROM OLD.release_digest THEN
                RAISE EXCEPTION 'reservation % release_digest is immutable', OLD.id
                    USING ERRCODE = '23514';
            END IF;
            RETURN NEW;
        END;
        $$;

        CREATE OR REPLACE FUNCTION sprintctl_work_decision_release_guard()
        RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            IF NEW.work_item_id IS NULL OR NEW.legacy_source IS NOT NULL
               OR COALESCE(current_setting('sprintctl.legacy_import', true), '') = 'on' THEN
                RETURN NEW;
            END IF;
            IF NEW.release_digest IS NOT NULL THEN
                IF NOT EXISTS (
                    SELECT 1 FROM work_release
                    WHERE repo_id = NEW.repo_id AND work_item_id = NEW.work_item_id
                      AND release_digest = NEW.release_digest
                ) THEN
                    RAISE EXCEPTION 'release % is not a release of work item %',
                        NEW.release_digest, NEW.work_item_id
                        USING ERRCODE = '23514';
                END IF;
            ELSIF EXISTS (
                SELECT 1 FROM work_release wr
                WHERE wr.repo_id = NEW.repo_id AND wr.work_item_id = NEW.work_item_id
                  AND wr.revise_count = (
                      SELECT COUNT(*) FROM work_decision d
                      WHERE d.repo_id = NEW.repo_id AND d.work_item_id = NEW.work_item_id
                        AND d.kind = 'revise'
                  )
            ) THEN
                RAISE EXCEPTION 'work item % has a current release; a decision must bind it',
                    NEW.work_item_id
                    USING ERRCODE = '23514';
            END IF;
            RETURN NEW;
        END;
        $$;
        """
    )
    cur.execute("DROP TRIGGER IF EXISTS reservation_release_guard ON reservation")
    cur.execute(
        "CREATE TRIGGER reservation_release_guard BEFORE INSERT OR UPDATE ON reservation "
        "FOR EACH ROW EXECUTE FUNCTION sprintctl_reservation_release_guard()"
    )
    cur.execute("DROP TRIGGER IF EXISTS work_decision_release_guard ON work_decision")
    cur.execute(
        "CREATE TRIGGER work_decision_release_guard BEFORE INSERT ON work_decision "
        "FOR EACH ROW EXECUTE FUNCTION sprintctl_work_decision_release_guard()"
    )
    for table in ("work_release", "release_commit"):
        cur.execute(f"DROP TRIGGER IF EXISTS {table}_immutable ON {table}")
        cur.execute(
            f"CREATE TRIGGER {table}_immutable BEFORE UPDATE OR DELETE ON {table} "
            "FOR EACH ROW EXECUTE FUNCTION sprintctl_release_immutable()"
        )
        cur.execute(f"DROP TRIGGER IF EXISTS {table}_no_truncate ON {table}")
        cur.execute(
            f"CREATE TRIGGER {table}_no_truncate BEFORE TRUNCATE ON {table} "
            "FOR EACH STATEMENT EXECUTE FUNCTION sprintctl_release_immutable()"
        )
        cur.execute(f"DROP TRIGGER IF EXISTS guard_integration_test_scope_{table} ON {table}")
        cur.execute(
            f"""
            DO $$
            BEGIN
                IF to_regprocedure('sprintctl_guard_integration_test_scope()') IS NOT NULL THEN
                    CREATE TRIGGER guard_integration_test_scope_{table}
                        BEFORE INSERT OR UPDATE OF repo_id ON {table}
                        FOR EACH ROW EXECUTE FUNCTION sprintctl_guard_integration_test_scope();
                END IF;
            END $$;
            """
        )


def _apply_schema_version_16(cur: Any) -> None:
    """Legacy re-mark (S3 PR5): one authored decision on a legacy done item.

    A legacy item that was already done when decisions arrived has no
    decision, and schema 14 refused to bind one.  This replaces only the body
    of the row guard so such an item may take exactly one terminal decision
    that names it, carries a rationale and at least one evidence digest, and
    is not a folded legacy decision.  The item stays done.  The rest of the
    guard is unchanged: done still needs a decision, and a bound terminal
    decision is immutable, which is what makes the re-mark one-shot.

    It also narrows the archive-import exemption of the decision release
    guard to decisions about legacy rows (``import_ndjson`` is its only
    user).

    Both statements are ``CREATE OR REPLACE FUNCTION``: no table changes and
    no table lock is taken, so the 5s migration lock timeout is never at
    risk from served traffic.  The row guard refuses nothing the old body
    allowed, so a pod still running the previous release keeps working while
    this commits; only an operator-run import of an inconsistent archive is
    refused that was admitted before.
    """
    cur.execute(
        """
        CREATE OR REPLACE FUNCTION sprintctl_work_item_terminal_guard()
        RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            IF TG_OP = 'INSERT' THEN
                IF NEW.legacy
                   AND COALESCE(current_setting('sprintctl.legacy_import', true), '') <> 'on' THEN
                    RAISE EXCEPTION 'work_item.legacy is set only by the schema 14 migration';
                END IF;
                RETURN NEW;
            END IF;
            IF NEW.legacy IS DISTINCT FROM OLD.legacy THEN
                RAISE EXCEPTION 'work_item.legacy is immutable';
            END IF;
            IF OLD.status = 'done' AND NEW.status IS DISTINCT FROM 'done' THEN
                RAISE EXCEPTION 'work item % is terminal; done cannot transition to %',
                    OLD.id, NEW.status;
            END IF;
            IF OLD.status IS DISTINCT FROM 'done' AND NEW.status = 'done'
               AND NEW.terminal_decision_id IS NULL THEN
                RAISE EXCEPTION 'work item % cannot become done without a terminal decision', OLD.id
                    USING ERRCODE = '23514';
            END IF;
            IF OLD.terminal_decision_id IS NOT NULL AND (
                   NEW.terminal_decision_id IS DISTINCT FROM OLD.terminal_decision_id
                   OR NEW.resolution IS DISTINCT FROM OLD.resolution
               ) THEN
                RAISE EXCEPTION 'work item % terminal decision is immutable', OLD.id;
            END IF;
            -- A row that was done before decisions existed binds a decision
            -- only by re-mark: a legacy row, an authored terminal decision
            -- about it (written first, in this transaction), with a
            -- rationale and evidence.  Once bound it is immutable (above).
            IF OLD.status = 'done' AND OLD.terminal_decision_id IS NULL
               AND NEW.terminal_decision_id IS NOT NULL
               AND NOT (
                   OLD.legacy AND EXISTS (
                       SELECT 1 FROM work_decision d
                       WHERE d.repo_id = NEW.repo_id AND d.id = NEW.terminal_decision_id
                         AND d.work_item_id = OLD.id
                         AND d.kind IN ('accept', 'reject', 'withdraw', 'supersede')
                         AND d.legacy_source IS NULL
                         -- Blank means only whitespace, tabs, newlines
                         -- and no-break spaces included.
                         AND btrim(d.rationale, E' \t\n\r\f\v' || chr(160)) <> ''
                         -- Every evidence element is a SHA-256 digest.
                         AND jsonb_array_length(d.evidence_digests) > 0
                         AND NOT EXISTS (
                             SELECT 1 FROM jsonb_array_elements(d.evidence_digests) e
                             WHERE jsonb_typeof(e) <> 'string'
                                OR (e #>> '{}') !~ '^[0-9a-f]{64}$'
                         )
                   )
               ) THEN
                RAISE EXCEPTION 'done work item % takes a decision only as a legacy re-mark with a rationale and evidence',
                    OLD.id
                    USING ERRCODE = '23514';
            END IF;
            RETURN NEW;
        END;
        $$;

        -- import_ndjson's legacy switch used to exempt every decision it
        -- carried from the release binding.  It now exempts only decisions
        -- about rows that are legacy; an imported decision about any other
        -- item must name a release of that item, or bind its current one,
        -- exactly as it had to when it was first recorded.  Import inserts
        -- items and releases before decisions, so the check sees them.
        CREATE OR REPLACE FUNCTION sprintctl_work_decision_release_guard()
        RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            IF NEW.work_item_id IS NULL OR NEW.legacy_source IS NOT NULL THEN
                RETURN NEW;
            END IF;
            IF COALESCE(current_setting('sprintctl.legacy_import', true), '') = 'on'
               AND EXISTS (
                   SELECT 1 FROM work_item
                   WHERE repo_id = NEW.repo_id AND id = NEW.work_item_id AND legacy
               ) THEN
                RETURN NEW;
            END IF;
            IF NEW.release_digest IS NOT NULL THEN
                IF NOT EXISTS (
                    SELECT 1 FROM work_release
                    WHERE repo_id = NEW.repo_id AND work_item_id = NEW.work_item_id
                      AND release_digest = NEW.release_digest
                ) THEN
                    RAISE EXCEPTION 'release % is not a release of work item %',
                        NEW.release_digest, NEW.work_item_id
                        USING ERRCODE = '23514';
                END IF;
            ELSIF EXISTS (
                SELECT 1 FROM work_release wr
                WHERE wr.repo_id = NEW.repo_id AND wr.work_item_id = NEW.work_item_id
                  AND wr.revise_count = (
                      SELECT COUNT(*) FROM work_decision d
                      WHERE d.repo_id = NEW.repo_id AND d.work_item_id = NEW.work_item_id
                        AND d.kind = 'revise'
                  )
            ) THEN
                RAISE EXCEPTION 'work item % has a current release; a decision must bind it',
                    NEW.work_item_id
                    USING ERRCODE = '23514';
            END IF;
            RETURN NEW;
        END;
        $$;
        """
    )


